#!/usr/bin/env python3
"""Hold the files over 1,000 lines to the list of the ones that stay.

A file over LIMIT lines (1,000) is one of two kinds: a file someone weighed
and keeps whole, with a reason, or one that grew past the line unseen.
tools/check_sizes.txt lists the first kind.  This tool counts the lines of
every file git tracks, as `wc -l` does, and compares.

    tools/check_sizes.py            every file over 1,000 lines and its entry
    tools/check_sizes.py --check    and exit 1 on any failure below

It fails on

- a file over 1,000 lines that the list does not name, unless an exclusion
  covers it or it is generated;
- a listed file at or under 1,000 lines, or not in the tree;
- a listed file whose count is outside the figure and tolerance its entry
  records ("2422 +-100"; "none" records no figure);
- a listed file that is generated;
- an exclusion that covers no file over 1,000 lines;
- a line of the list that is not an entry, an exclusion or a comment, and
  a path listed twice.

The list, one line each, fields split by " | ":

    path | 2422 +-100 | the reason it stays whole
    path | none | the reason it stays whole
    exclude glob | the reason no file it covers is counted

A glob is matched with fnmatch against the path from the repository root,
so `*` crosses `/`.  A file with a NUL byte is binary and not counted.

Generated files are the generators' to hold, not the list's: a file whose
first 10 lines say "Generated by tools/gen_<name>.py" is left out when that
generator exists, names the file, has a --check mode and is run with
--check in .github/workflows/ci.yml.  A file that says so and fails one of
these fails the check.

SPDX-License-Identifier: MIT
"""

import argparse
import fnmatch
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "tools" / "check_sizes.txt"
CI = ROOT / ".github" / "workflows" / "ci.yml"
LIMIT = 1000
HEAD_LINES = 10


def die(msg: str) -> None:
    sys.exit(f"check_sizes: {msg}")


def tracked() -> list:
    """Every path git tracks under ROOT, relative and with '/'."""
    try:
        out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z"],
                             capture_output=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError) as exc:
        die(f"git ls-files failed: {exc}")
    return [p for p in out.decode("utf-8").split("\0") if p]


def count(data: bytes) -> int | None:
    """Lines as `wc -l` counts them; None for a binary file."""
    if b"\0" in data:
        return None
    return data.count(b"\n")


def parse_list(text: str) -> tuple:
    """(entries, excludes, errors).  entries: {path: (figure or None,
    tolerance, reason, line)}; excludes: [(glob, reason, line)]."""
    entries, excludes, errors = {}, [], []
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        fields = [f.strip() for f in line.split(" | ")]
        if fields[0].startswith("exclude "):
            glob = fields[0][len("exclude "):].strip()
            if len(fields) != 2 or not glob or not fields[1]:
                errors.append(f"{LIST.name}:{n}: an exclusion is "
                              f"'exclude glob | reason'")
                continue
            excludes.append((glob, fields[1], n))
            continue
        if len(fields) != 3 or not fields[0] or not fields[2]:
            errors.append(f"{LIST.name}:{n}: an entry is 'path | lines | "
                          f"reason'")
            continue
        path, size, reason = fields
        m = re.fullmatch(r"(\d[\d,]*)\s*\+-\s*(\d[\d,]*)", size)
        if size == "none":
            figure, tol = None, 0
        elif m:
            figure, tol = (int(m.group(1).replace(",", "")),
                           int(m.group(2).replace(",", "")))
        else:
            errors.append(f"{LIST.name}:{n}: lines is 'none' or "
                          f"'figure +-tolerance', not {size!r}")
            continue
        if path in entries:
            errors.append(f"{LIST.name}:{n}: {path} is listed twice")
            continue
        entries[path] = (figure, tol, reason, n)
    return entries, excludes, errors


def generator_of(path: str, data: bytes, ci_text: str) -> tuple:
    """(generator, error) for a file whose head says a tools/gen_*.py
    generated it; (None, None) for any other file."""
    head = b"\n".join(data.split(b"\n", HEAD_LINES)[:HEAD_LINES])
    m = re.search(rb"Generated by (tools/gen_\w+\.py)", head)
    if m is None:
        return None, None
    gen = m.group(1).decode()
    src = ROOT / gen
    if not src.is_file():
        return gen, f"{path} says {gen} generates it; there is no {gen}"
    text = src.read_text(encoding="utf-8")
    if Path(path).name not in text:
        return gen, f"{path} says {gen} generates it; {gen} does not name it"
    if '"--check"' not in text:
        return gen, f"{path} says {gen} generates it; {gen} has no --check"
    if not re.search(re.escape(gen) + r"\s+--check\b", ci_text):
        return gen, (f"{path} says {gen} generates it; ci.yml does not run "
                     f"{gen} --check")
    return gen, None


def check(files: dict, list_text: str, ci_text: str) -> tuple:
    """(report, fails).  files: {path: bytes}.  report: (path, lines,
    what) for every file over LIMIT, longest first."""
    entries, excludes, fails = parse_list(list_text)
    sizes = {}
    for path, data in files.items():
        n = count(data)
        if n is not None:
            sizes[path] = n
    over = {p: n for p, n in sizes.items() if n > LIMIT}

    report = []
    used = set()
    for path in sorted(over, key=lambda p: (-over[p], p)):
        n = over[path]
        gen, error = generator_of(path, files[path], ci_text)
        if error:
            fails.append(error)
        if gen and path in entries:
            fails.append(f"{path} is generated by {gen}, which holds it; "
                         f"take it out of {LIST.name}")
        hit = [g for g, _, _ in excludes if fnmatch.fnmatchcase(path, g)]
        used.update(hit)
        if gen:
            what = f"generated by {gen}"
        elif path in entries:
            what = entries[path][2]
        elif hit:
            what = f"excluded by {hit[0]}"
        else:
            what = "NOT LISTED"
            fails.append(f"{path} is {n:,} lines, over {LIMIT:,}, and not "
                         f"in {LIST.name}: split it, or list it with the "
                         f"reason it stays whole")
        report.append((path, n, what))

    for path, (figure, tol, _, line) in entries.items():
        if path not in sizes:
            fails.append(f"{LIST.name}:{line}: {path} is not a text file in "
                         f"the tree; take it out")
            continue
        n = sizes[path]
        if n <= LIMIT:
            fails.append(f"{LIST.name}:{line}: {path} is {n:,} lines, at or "
                         f"under {LIMIT:,}; take it out")
        elif figure is not None and abs(n - figure) > tol:
            fails.append(f"{LIST.name}:{line}: {path} is {n:,} lines; the "
                         f"list records {figure:,} +-{tol:,}: update the "
                         f"figure")
    for glob, _, line in excludes:
        if glob not in used:
            fails.append(f"{LIST.name}:{line}: exclude {glob} covers no file "
                         f"over {LIMIT:,} lines; take it out")
    return report, fails


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the tree and tools/check_sizes.txt "
                         "disagree")
    args = ap.parse_args()
    files = {}
    for rel in tracked():
        path = ROOT / rel
        if path.is_file():
            files[rel] = path.read_bytes()
    report, fails = check(files, LIST.read_text(encoding="utf-8"),
                          CI.read_text(encoding="utf-8"))
    if not args.check:
        for path, n, what in report:
            print(f"{n:>6}  {path}  ({what})")
    for f in fails:
        print("FAIL " + f)
    print(f"check_sizes: {len(report)} files over {LIMIT:,} lines, "
          f"{len(fails)} failure(s)")
    return 1 if fails and args.check else 0


if __name__ == "__main__":
    sys.exit(main())
