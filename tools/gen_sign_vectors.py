#!/usr/bin/env python3
"""Write test/host/sign_vectors.h: ECDSA P-256 signatures from the openssl CLI.

The host test of shared/fwupdate/fw_sign.c checks the verifier against
signatures that openssl produced.  This tool makes two throw-away P-256 key
pairs and one P-384 key, signs 48 images with the first P-256 key and writes
the public keys and the signatures as C data.  The private keys exist only in
a temporary directory and are deleted when the tool ends; the header holds
public data only.

Image i has 64 + 13 * i bytes, byte j of it is (i * 31 + j * 7) & 0xFF.  The
test rebuilds the same bytes.

    python3 tools/gen_sign_vectors.py            # rewrite the header
    python3 tools/gen_sign_vectors.py --check    # verify the committed header
                                                 # against openssl, no write

SPDX-License-Identifier: MIT
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parent.parent
OUT = REPO / "test" / "host" / "sign_vectors.h"
COUNT = 48


def image(i: int) -> bytes:
    return bytes((i * 31 + j * 7) & 0xFF for j in range(64 + 13 * i))


def run(*args: str, data: bytes | None = None) -> bytes:
    return subprocess.run(args, input=data, check=True,
                          capture_output=True).stdout


def make(tmp: pathlib.Path) -> str:
    keys = []
    for n in ("a", "b"):
        prv = tmp / f"{n}.pem"
        pub = tmp / f"{n}.pub.pem"
        run("openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout",
            "-out", str(prv))
        run("openssl", "ec", "-in", str(prv), "-pubout", "-out", str(pub))
        keys.append((prv, pub))
    out = ["/* Generated by tools/gen_sign_vectors.py. Public data only.\n",
           " * SPDX-License-Identifier: MIT */\n",
           "#ifndef RCBENCH_SIGN_VECTORS_H\n",
           "#define RCBENCH_SIGN_VECTORS_H\n\n",
           "#include <stdint.h>\n\n",
           f"#define SV_COUNT {COUNT}u\n\n"]
    p384 = tmp / "c.pem"
    p384pub = tmp / "c.pub.pem"
    run("openssl", "ecparam", "-name", "secp384r1", "-genkey", "-noout",
        "-out", str(p384))
    run("openssl", "ec", "-in", str(p384), "-pubout", "-out", str(p384pub))
    for name, path in (("sv_pem_a", keys[0][1]), ("sv_pem_b", keys[1][1]),
                       ("sv_pem_p384", p384pub)):
        out.append(f"static const char {name}[] =\n")
        for line in path.read_text().splitlines():
            out.append(f'    "{line}\\n"\n')
        out.append(";\n\n")
    sigs = []
    for i in range(COUNT):
        s = run("openssl", "dgst", "-sha256", "-sign", str(keys[0][0]),
                data=image(i))
        sigs.append(s)
    out.append("\nstatic const uint8_t sv_sig_len[SV_COUNT] = {"
               + ", ".join(str(len(s)) for s in sigs) + "};\n")
    out.append("static const uint8_t sv_sig[SV_COUNT][72] = {\n")
    for s in sigs:
        out.append("    {" + ", ".join(f"0x{v:02X}" for v in s) + "},\n")
    out.append("};\n\n#endif\n")
    return "".join(out)


def main() -> int:
    check = "--check" in sys.argv[1:]
    if check:
        text = OUT.read_text()
        block = re.search(r"sv_pem_a\[\] =\n(.*?);", text, re.S).group(1)
        pem = "\n".join(re.findall(r'^\s*"(.*)\\n"$', block, re.M))
        ok = True
        with tempfile.TemporaryDirectory() as d:
            pub = pathlib.Path(d) / "a.pub.pem"
            pub.write_text(pem + "\n")
            sig_len = [int(x) for x in re.search(
                r"sv_sig_len\[SV_COUNT\] = \{(.*?)\}", text).group(1).split(
                ",")]
            rows = re.findall(r"^    \{(0x.*)\},$", text, re.M)
            for i in range(COUNT):
                sig = bytes(int(x, 16) for x in rows[i].split(","))[
                    :sig_len[i]]
                p = pathlib.Path(d) / "s.bin"
                p.write_bytes(sig)
                r = subprocess.run(
                    ["openssl", "dgst", "-sha256", "-verify", str(pub),
                     "-signature", str(p)], input=image(i),
                    capture_output=True)
                if r.returncode != 0:
                    print(f"sign_vectors.h: signature {i} does not verify")
                    ok = False
        print("sign_vectors.h: ok" if ok else "sign_vectors.h: drift")
        return 0 if ok else 1
    with tempfile.TemporaryDirectory() as d:
        OUT.write_text(make(pathlib.Path(d)))
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
