#!/usr/bin/env python3
"""Generate the M5Stack Dial's ring coverage tables as const C data.

The Dial's face carries six antialiased 1px rings at radii 118, 115, 112,
109, 106 and 103 pixels around the center of its 240 x 240 screen.  Each
ring is a table of pixels with one byte of coverage, sorted by angle from
12 o'clock clockwise (shared/gfx/include/gfx_ring.h).  This tool computes
the tables with the arithmetic of gfx_ring_build() and writes them to
shared/dial/dial_rings.c, so the tables live in flash and the Dial builds
none at boot.

    python3 tools/gen_dial_rings.py           # write the file
    python3 tools/gen_dial_rings.py --check   # fail if the file differs

The host suite compares the tables with gfx_ring_build()'s output, pixel by
pixel; CI (continuous integration) runs --check so the file and this tool
cannot drift apart.
"""

from __future__ import annotations

import argparse
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "shared" / "dial" / "dial_rings.c"
OUT_NAME = "shared/dial/dial_rings.c"

#: The screen's center, doubled: (119.5, 119.5) pixels (dial_face.h).
C2 = 239
#: Rings, the outermost radius and the pitch inward, pixels (dial_face.h).
RINGS = 6
R0 = 118
PITCH = 3
#: Angle units in one turn (GFX_RING_TURN).
TURN = 65536
#: Table entries per line of the generated file.
PER_LINE = 8


def lround(v: float) -> int:
    """Round half away from zero, as the C library's lround does.

    Args:
        v: the value, not negative

    Returns:
        the nearest integer, halves rounded up
    """
    f = math.floor(v)
    return f + 1 if v - f >= 0.5 else f


def angle(cx2: int, cy2: int, x: int, y: int) -> int:
    """Return a pixel's angle as gfx_ring_angle() does.

    Args:
        cx2: the center's x, doubled
        cy2: the center's y, doubled
        x: the pixel's column
        y: the pixel's row

    Returns:
        the angle from 12 o'clock clockwise, 0 to TURN - 1
    """
    dx = float(x) - float(cx2) / 2.0
    dy = float(y) - float(cy2) / 2.0
    a = math.atan2(dx, -dy)
    if a < 0.0:
        a += 2.0 * math.pi
    q = a * float(TURN) / (2.0 * math.pi)
    if q >= float(TURN - 1):
        return TURN - 1
    return int(q)


def ring(cx2: int, cy2: int, r: int) -> list[tuple[int, int, int]]:
    """Return one ring's table as gfx_ring_build() computes it.

    Args:
        cx2: the center's x, doubled
        cy2: the center's y, doubled
        r: the radius, pixels

    Returns:
        (x, y, coverage) per pixel, sorted by angle, then scan order
    """
    cx = float(cx2) / 2.0
    cy = float(cy2) / 2.0
    x0 = math.floor(cx - float(r) - 1.0)
    x1 = math.ceil(cx + float(r) + 1.0)
    y0 = math.floor(cy - float(r) - 1.0)
    y1 = math.ceil(cy + float(r) + 1.0)
    found = []
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            dx = float(x) - cx
            dy = float(y) - cy
            d = math.sqrt(dx * dx + dy * dy)
            cov = 1.0 - abs(d - float(r))
            if cov <= 0.0:
                continue
            c8 = lround(cov * 255.0)
            if c8 <= 0:
                continue
            found.append((angle(cx2, cy2, x, y), len(found), x, y,
                          min(c8, 255)))
    found.sort()
    return [(x, y, c) for _, _, x, y, c in found]


def emit() -> str:
    """Return the text of shared/dial/dial_rings.c.

    Returns:
        the C file
    """
    rings = [ring(C2, C2, R0 - PITCH * i) for i in range(RINGS)]
    total = sum(len(t) for t in rings)
    out = [
        "/**",
        " * @file",
        " * @brief The Dial's six ring coverage tables, const in flash.",
        " *",
        " * Generated by tools/gen_dial_rings.py -- do not edit by hand.",
        " *",
        " * %d pixels of 3 bytes: %d bytes.  Rings at radii" % (total,
                                                                 3 * total),
        " * %s pixels around (119.5, 119.5)," % ", ".join(
            str(R0 - PITCH * i) for i in range(RINGS)),
        " * each sorted by angle (gfx_ring.h).",
        " *",
        " * SPDX-License-Identifier: MIT",
        " */",
        "",
        '#include "dial_face.h"',
        "",
        "const uint16_t dial_ring_n[DIAL_RINGS] = {",
        "    " + ", ".join("%du" % len(t) for t in rings),
        "};",
        "",
        "const gfx_ring_px_t dial_ring_px[] = {",
    ]
    for i, t in enumerate(rings):
        out.append("    /* ring %d, radius %d */" % (i, R0 - PITCH * i))
        for k in range(0, len(t), PER_LINE):
            out.append("    " + " ".join(
                "{%d, %d, %d}," % p for p in t[k:k + PER_LINE]))
    out.append("};")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    """Write the tables, or check the checked-in file with --check.

    Args:
        argv: the arguments; None takes the command line's

    Returns:
        0 when written or up to date, 1 when --check finds a difference
    """
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="fail if %s differs from the generator" % OUT_NAME)
    args = ap.parse_args(argv)
    text = emit()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("%s is out of date; run tools/gen_dial_rings.py" % OUT_NAME,
                  file=sys.stderr)
            return 1
        print("%s is up to date" % OUT_NAME)
        return 0
    OUT.write_text(text)
    print("wrote %s" % OUT_NAME)
    return 0


if __name__ == "__main__":
    sys.exit(main())
