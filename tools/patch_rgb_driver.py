#!/usr/bin/env python3
"""Compile ESP-IDF's RGB panel driver with a clean restart.

The panel scans out of two bounce buffers of 10 lines each, which an
interrupt handler refills from the frame buffer in PSRAM (pseudo-static
random-access memory) on every DMA (direct memory access) end of buffer,
48 times a frame.  At each VBlank (vertical blanking interval) the driver
counts those refills.  Fewer than 48 means a refill was lost -- the
handler was masked for longer than one buffer, 512 us at the 16 MHz pixel
clock, by a main-flash operation or by anything else that holds the
interrupts off -- and the driver restarts the scan.

ESP-IDF v5.4 and v5.5 restart it through a "restart link" on the
ESP32-S3: lcd_ll_fifo_reset() empties the LCD FIFO (first-in, first-out
buffer), then the DMA resumes 17 px (LCD_LL_FIFO_DEPTH + 1) into bounce
buffer 0, on the assumption that the FIFO still holds the first 17.  It
does not, so the scan runs 17 px ahead of the panel: the picture sits
17 px to the left and the tail of every line wraps one line down.  The
stream is a ring and every later frame counts its 48 refills, so nothing
corrects it until the next power-on.  A restart on every VBlank
(CONFIG_LCD_RGB_RESTART_IN_VSYNC) showed the same 17 px shift on every
frame on this board.

The one start that leaves the picture in place is the one the panel gets
at boot, lcd_rgb_panel_start_transmission(): stop and reset the LCD, empty
its FIFO, refill both bounce buffers from the top of the frame, start the
DMA at the head of the bounce-buffer ring and then the LCD.  This tool
writes a copy of the driver in which every restart is that start:

  restart   the restart check returns through
            lcd_rgb_panel_start_transmission() and counts the restart in
            rcbench_lcd_rgb_restarts.  The restart link is never started.
  stale-eof the start clears an end-of-buffer interrupt the old stream
            raised and nothing has handled yet, and zeroes the refill
            count.  Left pending, that interrupt would refill a third
            buffer after the start and run the picture 10 lines ahead
            until the next power-on.
  vsync     the start clears a VBlank interrupt its own stop and start
            may raise.  Handled, it would find no refill counted and
            restart again.

The copy carries an rcbench_ prefix on its public functions
(firmware/panel/components/display/include/rgb_panel_rcbench.h), so
ESP-IDF's own copy in libesp_lcd.a is not linked in its place.

Each patch replaces text that occurs exactly once in the source.  A
source where one occurs zero times or more than once -- an ESP-IDF
release that changed the driver -- fails the build with the patch's
name, rather than building a driver without the fix.

    patch_rgb_driver.py \\
        --source $IDF_PATH/components/esp_lcd/rgb/esp_lcd_panel_rgb.c \\
        --out build/esp_lcd_panel_rgb_rcbench.c

The output is written only when its text changes, so a configure run
that changes nothing rebuilds nothing.

SPDX-License-Identifier: MIT
"""

from __future__ import annotations

import argparse
import pathlib
import sys

PRELUDE = """\
/*
 * Generated by tools/patch_rgb_driver.py from ESP-IDF's
 * components/esp_lcd/rgb/esp_lcd_panel_rgb.c (Apache-2.0, Espressif
 * Systems).  Edit the tool, not this file.
 */
#include "rgb_panel_rcbench.h"
#include "sdkconfig.h"
#include "esp_err.h"
#include "esp_private/gdma.h"
#include "hal/gdma_ll.h"

#if !CONFIG_IDF_TARGET_ESP32S3
#error "the clean restart clears the ESP32-S3's AHB GDMA channel"
#endif
#if CONFIG_LCD_RGB_ISR_IRAM_SAFE
/* The clean restart runs flash-resident code from the VBlank interrupt,
 * which ESP-IDF masks while the cache is off only when this is off. */
#error "CONFIG_LCD_RGB_ISR_IRAM_SAFE must stay off"
#endif

volatile uint32_t rcbench_lcd_rgb_restarts;

/* An end-of-buffer interrupt of the stream before a start, not yet
 * handled.  The DMA has been reset, so the next one is the new stream's,
 * one bounce buffer (10 lines) after the start. */
static void rcbench_gdma_drop_eof(gdma_channel_handle_t chan)
{
    int id = -1;
    if (gdma_get_group_channel_id(chan, NULL, &id) == ESP_OK && id >= 0) {
        gdma_ll_tx_clear_interrupt_status(&GDMA, (uint32_t)id,
                                          GDMA_LL_EVENT_TX_EOF);
    }
}

"""

# (name, text that occurs once, what replaces it)
PATCHES: tuple[tuple[str, str, str], ...] = (
    (
        "restart",
        "    if (!do_restart) {\n"
        "        return;\n"
        "    }\n",
        "    if (!do_restart) {\n"
        "        return;\n"
        "    }\n"
        "    /* rcbench: the start the panel gets at boot, never the restart\n"
        "     * link below (tools/patch_rgb_driver.py). */\n"
        "    rcbench_lcd_rgb_restarts++;\n"
        "    lcd_rgb_panel_start_transmission(panel);\n"
        "    return;\n",
    ),
    (
        "stale-eof",
        "    gdma_reset(rgb_panel->dma_chan);\n"
        "    lcd_ll_stop(rgb_panel->hal.dev);\n",
        "    gdma_reset(rgb_panel->dma_chan);\n"
        "    /* rcbench: no refill of the old stream after this point. */\n"
        "    rcbench_gdma_drop_eof(rgb_panel->dma_chan);\n"
        "    rgb_panel->bb_eof_count = 0;\n"
        "    lcd_ll_stop(rgb_panel->hal.dev);\n",
    ),
    (
        "vsync",
        "    lcd_ll_start(rgb_panel->hal.dev);\n"
        "}\n",
        "    lcd_ll_start(rgb_panel->hal.dev);\n"
        "    /* rcbench: the next VBlank counted ends this frame. */\n"
        "    lcd_ll_clear_interrupt_status(rgb_panel->hal.dev,\n"
        "                                  LCD_LL_EVENT_VSYNC_END);\n"
        "}\n",
    ),
)


class PatchError(Exception):
    """A patch's text does not occur exactly once in the source."""


def patch(source: str) -> str:
    """The driver with every patch applied and the prelude in front."""
    out = source
    for name, old, new in PATCHES:
        n = out.count(old)
        if n != 1:
            raise PatchError(
                f"patch '{name}': its text occurs {n} times in the driver, "
                "not once; this ESP-IDF release changed the RGB driver")
        out = out.replace(old, new)
    return PRELUDE + out


def write_if_changed(path: pathlib.Path, text: str) -> bool:
    """Write @p text to @p path unless it holds that already."""
    try:
        if path.read_text(encoding="utf-8") == text:
            return False
    except FileNotFoundError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--source", type=pathlib.Path, required=True,
                    help="ESP-IDF's esp_lcd_panel_rgb.c")
    ap.add_argument("--out", type=pathlib.Path, required=True,
                    help="the patched copy to write")
    args = ap.parse_args(argv)
    try:
        text = patch(args.source.read_text(encoding="utf-8"))
    except (OSError, PatchError) as e:
        print(f"patch_rgb_driver: {e}", file=sys.stderr)
        return 1
    write_if_changed(args.out, text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
