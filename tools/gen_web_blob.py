#!/usr/bin/env python3
"""Generate the C file that carries the Wi-Fi page's file manager.

The page's script and style sheet are written as plain files under
shared/webaccess/web: app.css, hl.js and app.js.  The panel serves them
inside the page (wa_app.c), so they are compiled in as C strings:
shared/webaccess/wa_web_blob.c holds each file as an array of pieces of at
most PIECE_MAX bytes, cut at line ends and ended by NULL.

    python3 tools/gen_web_blob.py            # regenerate the C file
    python3 tools/gen_web_blob.py --check    # the checked-in file agrees
    python3 tools/gen_web_blob.py --sizes    # bytes of each file as served

What is left out on the way: blank lines, the leading spaces of each line,
a JavaScript line that is a `//` comment alone and a CSS `/* */` comment.
A line of code keeps its trailing comment.  The sources are ASCII; a byte
over 0x7E, a control character other than LF, and the text "</script",
"</style" or "<!--" in either kind, which would end the page's element
early, fail the run.

The generated file is checked in, so the firmware build needs no Python.
CI (continuous integration) runs --check so the two cannot drift apart.

SPDX-License-Identifier: MIT
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SRC = "shared/webaccess/web"
OUT = "shared/webaccess/wa_web_blob.c"

# The arrays, in the order the page writes them: name, source file, kind.
FILES = (
    ("wa_web_css", "app.css", "css"),
    ("wa_web_hl_js", "hl.js", "js"),
    ("wa_web_app_js", "app.js", "js"),
)

# Bytes of one C string at most: well under the 4,095 a C compiler takes in
# a literal without a warning.
PIECE_MAX = 2000

FORBIDDEN = ("</script", "</style", "<!--")


class Bad(Exception):
    """A source the page cannot carry."""


def served(text: str, kind: str, name: str = "") -> str:
    """The text of one source as the page carries it.

    Args:
        text: The source file's text.
        kind: "js" or "css".
        name: The file's name, for the messages.

    Returns:
        The lines kept, each without its leading spaces, joined by LF and
        ended by one.

    Raises:
        Bad: A byte the page cannot carry, or a sequence that ends its
            element.
    """
    for i, ch in enumerate(text):
        if ch != "\n" and not " " <= ch <= "~":
            line = text.count("\n", 0, i) + 1
            raise Bad(f"{name}:{line}: byte {ord(ch):#x} is not printable "
                      "ASCII")
    low = text.lower()
    for seq in FORBIDDEN:
        if seq in low:
            line = text.count("\n", 0, low.index(seq)) + 1
            raise Bad(f"{name}:{line}: {seq!r} would end the page's element")
    if kind == "css":
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    out = []
    for line in text.split("\n"):
        line = line.strip(" ")
        if line == "" or (kind == "js" and line.startswith("//")):
            continue
        out.append(line)
    return "\n".join(out) + "\n"


def pieces(text: str) -> list[str]:
    """The text cut at line ends into pieces of at most PIECE_MAX bytes.

    Args:
        text: Served text, every line ended by LF.

    Returns:
        The pieces in order; their sum is the text.

    Raises:
        Bad: A line longer than PIECE_MAX.
    """
    out: list[str] = []
    cur = ""
    for line in text.splitlines(keepends=True):
        if len(line) > PIECE_MAX:
            raise Bad(f"a line of {len(line)} bytes is longer than "
                      f"{PIECE_MAX}")
        if len(cur) + len(line) > PIECE_MAX:
            out.append(cur)
            cur = ""
        cur += line
    if cur:
        out.append(cur)
    return out


def c_string(s: str) -> str:
    """A C string literal of @p s, split into source lines at each LF.

    Args:
        s: Printable ASCII and LF.

    Returns:
        One or more adjacent literals, each on its own line.
    """
    lits = []
    for line in s.splitlines(keepends=True):
        body = (line.replace("\\", "\\\\").replace('"', '\\"')
                .replace("?", "\\?").replace("\n", "\\n"))
        lits.append(f'    "{body}"')
    return "\n".join(lits)


def emit(sources: dict[str, str]) -> str:
    """The C file.

    Args:
        sources: The text of each file of FILES, by file name.

    Returns:
        The file's text.
    """
    out = [
        "/**",
        " * @file",
        " * @brief Generated by tools/gen_web_blob.py from",
        " *        shared/webaccess/web: do not edit.  The file manager of the",
        " *        Wi-Fi page as wa_app.c writes it, each file in pieces ended",
        " *        by NULL.",
        " *",
        " * SPDX-License-Identifier: MIT",
        " */",
        "",
        '#include "wa_web_blob.h"',
        "",
        "#include <stddef.h>",
    ]
    for var, name, kind in FILES:
        text = served(sources[name], kind, name)
        out.append("")
        out.append(f"/** @brief {name}, {len(text)} bytes. */")
        out.append(f"const char *const {var}[] = {{")
        for p in pieces(text):
            out.append(c_string(p) + ",")
        out.append("    NULL,")
        out.append("};")
    return "\n".join(out) + "\n"


def read_sources(root: pathlib.Path) -> dict[str, str]:
    """The text of each file of FILES under @p root.

    Args:
        root: The folder of the sources.

    Returns:
        The texts by file name.
    """
    return {name: (root / name).read_text(encoding="utf-8")
            for _, name, _ in FILES}


def main(argv: list[str] | None = None) -> int:
    """Run the tool.

    Args:
        argv: The arguments; sys.argv[1:] when None.

    Returns:
        The exit code: 0, or 1 for a bad source or a file out of date.
    """
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="fail if the checked-in C file differs")
    ap.add_argument("--sizes", action="store_true",
                    help="print the bytes of each file as served")
    ap.add_argument("--root", type=pathlib.Path, default=REPO,
                    help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    try:
        sources = read_sources(args.root / SRC)
        text = emit(sources)
    except (Bad, OSError) as e:
        print(f"gen_web_blob: {e}", file=sys.stderr)
        return 1
    out = args.root / OUT
    if args.sizes:
        total = 0
        for _, name, kind in FILES:
            n = len(served(sources[name], kind, name))
            total += n
            print(f"{name}: {n} bytes")
        print(f"total: {total} bytes")
        return 0
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date: run tools/gen_web_blob.py",
                  file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
