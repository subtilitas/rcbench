static void tap(int x, int y)
{
    touch_event_t e = { .type = TOUCH_EVENT_DOWN,
                        .point = { .id = 1, .x = (int16_t)x,
                                   .y = (int16_t)y, .strength = 40 } };
    ui_router_event(&e);
    e.type = TOUCH_EVENT_UP;
    ui_router_event(&e);
}

/* A tap on the SETUP tile of category @p cat. */
static void setup_tile(setting_cat_t cat)
{
    gfx_rect_t r = gfx_rect_make(0, 0, 0, 0);
    (void)settings_hub_slot(settings_hub_cat_tile(cat), &r);
    tap(r.x + r.w / 2, UI_BAND_H + r.y + r.h / 2);
}

/* A finger drawn from @p y0 to @p y1 at @p x, in steps a controller would
 * report. */
static void drag(int x, int y0, int y1)
{
    touch_event_t e = { .type = TOUCH_EVENT_DOWN,
                        .point = { .id = 1, .x = (int16_t)x,
                                   .y = (int16_t)y0, .strength = 40 } };
    ui_router_event(&e);
    const int step = (y1 > y0) ? 8 : -8;
    e.type = TOUCH_EVENT_MOVE;
    for (int y = y0 + step; (step > 0) ? (y < y1) : (y > y1); y += step) {
        e.point.y = (int16_t)y;
        ui_router_event(&e);
    }
    e.point.y = (int16_t)y1;
    ui_router_event(&e);
    e.type = TOUCH_EVENT_UP;
    ui_router_event(&e);
}


