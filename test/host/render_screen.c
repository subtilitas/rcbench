/**
 * @brief BALANCE and the ANALYSER: the cells and the received frames.
 * @param id   The screen of the shot.
 * @param view The golden's name.
 */
static void pose_analyser_views(ui_screen_id_t id, const char *view)
{
    if (id == SCREEN_BALANCE && strcmp(view, "balance") != 0) {
        ui_router_goto(SCREEN_BALANCE);
        if (strcmp(view, "balance-rig") == 0) {
            tap(IN_TAB_X(1), UI_BAND_H + IN_TAB_Y);
        } else if (strcmp(view, "balance-aircraft") == 0) {
            tap(IN_TAB_X(2), UI_BAND_H + IN_TAB_Y);
        } else if (strcmp(view, "balance-keypad") == 0) {
            /* The blade count tapped, 5 typed. */
            const gfx_rect_t r = balance_screen_blades_rect();
            tap(r.x + r.w / 2, UI_BAND_H + r.y + r.h / 2);
            kp_type(balance_screen_keypad(), "5");
        } else if (strcmp(view, "balance-edf") == 0) {
            /* A five-blade ducted fan: the duct, and a rotor whose blades
             * are not reachable. */
            tap(BL_EDF_X, UI_BAND_H + BL_ROTOR_Y);
            for (int i = 0; i < 3; ++i) {
                tap(BL_UP_X, UI_BAND_H + BL_BLADES_Y);
            }
        }
    }

    /* analyser-silent: nothing decoded, as on a bench, where no firmware
     * feeds the screen. */
    if (id == SCREEN_ANALYSER && strcmp(view, "analyser-silent") != 0) {
        /*
         * Fed through the real S.BUS decoder frame by frame with the channels
         * moving; a still frame shows sixteen straight lines.
         */
        sbus_decoder_t dec;
        sbus_decoder_reset(&dec);
        uint32_t us = 100000u;

        /* 212 frames: every lane's 200 samples filled. */
        for (unsigned t = 0; t < 212u; ++t) {
            uint16_t ch[SBUS_CHANNELS];
            for (unsigned i = 0; i < SBUS_CHANNELS; ++i) {
                ch[i] = 1024;                       /* neutral */
            }
            /* A stick swept across the window. */
            ch[1] = (uint16_t)(1024 + (int)(600.0f
                        * sinf((float)t * 0.06f)));
            /* A switch thrown a third of the way in. */
            ch[4] = (t > 70u) ? 1811 : 172;
            /* A knob wound slowly. */
            ch[7] = (uint16_t)(400 + t * 6u);
            /* One frame with a spike: the glitch a lane makes findable. */
            if (t == 160u) {
                ch[10] = 1811;
            }

            uint8_t raw[SBUS_FRAME_BYTES];
            memset(raw, 0, sizeof(raw));
            raw[0] = SBUS_HEADER;
            for (unsigned i = 0; i < SBUS_CHANNELS; ++i) {
                const unsigned bit = i * 11u;
                for (unsigned b = 0; b < 11u; ++b) {
                    if (ch[i] & (1u << b)) {
                        const unsigned at = bit + b;
                        raw[1u + at / 8u] |= (uint8_t)(1u << (at % 8u));
                    }
                }
            }
            raw[23] = SBUS_FLAG_CH17;
            /*
             * The failsafe state has a golden of its own.  A receiver in
             * failsafe sends well-formed values it generates itself, and
             * the presentation of that state is held between releases.
             */
            if (strcmp(view, "analyser-failsafe") == 0) {
                raw[23] |= SBUS_FLAG_FAILSAFE;
            }
            /* analyser-lost: the receiver flags a damaged frame. */
            if (strcmp(view, "analyser-lost") == 0) {
                raw[23] |= SBUS_FLAG_FRAME_LOST;
            }

            sbus_frame_t frame;
            bool got = false;
            us += SBUS_GAP_US * 2u;          /* the gap that starts a frame */
            for (unsigned i = 0; i < SBUS_FRAME_BYTES; ++i) {
                if (sbus_decode_byte(&dec, raw[i], us, &frame)) {
                    got = true;
                }
                us += 120u;
            }
            if (got) {
                analyser_screen_push(&frame, &dec, raw, SBUS_FRAME_BYTES,
                                     t * 14u);
            }
        }
    }
}

/**
 * @brief The rbmod carrier's views: the board recorded and its interface
 *        pins held, before the screen is posed.  outputs-rbmod: SERVO PWM
 *        on PWM01 and PWM02, DSHOT300 on PWM04, MOTOR PWM picked and PWM03
 *        tapped, refused for slice 2.  outputs-rbmod-port: PROG PORT 1 on
 *        GP13.  setup-rbmod: the hub with LAYOUT in PICK A PIN's place.
 *        setup-rbmod-iface: INTERFACES with its pins soldered.
 *        layout-rbmod: LAYOUT with the same binding.  supply-rbmod:
 *        SUPPLY with the PROG PORTS 5V line.  setup-sensors-rbmod:
 *        SENSORS with 0x40 soldered and its channels on the rails.
 * @param id   The screen of the shot.
 * @param view The golden's name.
 * @return true when the view is one of these and OUTPUTS is posed.
 */
static bool pose_carrier_views(ui_screen_id_t id, const char *view)
{
    if (strstr(view, "-rbmod") == NULL) {
        return false;
    }
    const uint16_t brd = OUTBIND_BOARD_RBMOD;
    ui_board_set(brd);
    (void)ui_board_apply_pins(NULL);
    outbind_t b;
    outbind_init(&b);
    outbind_set_board(&b, brd);
    outbind_set_proto(&b, proto_named("SERVO PWM"));
    (void)outbind_toggle(&b, outbind_index_of(brd, 2u));
    (void)outbind_toggle(&b, outbind_index_of(brd, 4u));
    outbind_set_proto(&b, proto_named("DSHOT300"));
    (void)outbind_toggle(&b, outbind_index_of(brd, 1u));
    outputs_screen_set_binding(&b);
    /* SUPPLY names the ports' own 5V, off between sessions. */
    supply_screen_set_prog_5v((uint8_t)PROG_SUPPLY_OFF, 21u);
    if (id != SCREEN_OUTPUTS) {
        return false;
    }
    port_view_t v;
    port_view_unknown(&v);
    v.count    = 4u;
    v.has_func = true;
    v.has_dshot = true;
    static const uint8_t pins[LINK_PG_PORTS_MAX] = { 13u, 14u, 15u, 0u };
    for (unsigned n = 0; n < LINK_PG_PORTS_MAX; ++n) {
        v.pin[n]  = pins[n];
        v.func[n] = (uint8_t)LINK_PG_FN_NONE;
    }
    port_view_set(&v);
    outputs_screen_set_prog_ports(4u, pins);
    outputs_screen_set_result(OUTPUTS_OK);
    if (strcmp(view, "outputs-rbmod-port") == 0) {
        outputs_screen_open_on_port(0u);
        ui_router_goto(SCREEN_OUTPUTS);
        return true;
    }
    ui_router_goto(SCREEN_OUTPUTS);
    outputs_screen_select(proto_named("MOTOR PWM"));
    /* PWM03, the grid's third cell. */
    touch_event_t d = { TOUCH_EVENT_DOWN,
                        { 0, (int16_t)(OU_CELL_X(2) + 60),
                          (int16_t)(UI_BAND_H + OU_CELL_Y(2) + 26), 40 },
                        0u };
    touch_event_t u = d;
    u.type = TOUCH_EVENT_UP;
    ui_router_event(&d);
    ui_router_event(&u);
    return true;
}

