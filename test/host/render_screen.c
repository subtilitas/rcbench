/*
 * A help bubble of the band, opened by a tap on its chip over the menu.
 * The status is the view's: band-fault has the three bits this release
 * sets, band-fault-all every bit and one this panel has no name for --
 * the tallest bubble there is.
 */
static void band_view(const char *view, ui_bench_status_t *st)
{
    ui_band_chip_t chip = UI_BAND_CHIP_LINK;
    /* An IOmcu that has refused 37 frames, as on motor-refused, and
     * one at the widest count. */
    if (strcmp(view, "band-link-refused") == 0) {
        st->link_refused = 37u;
    } else if (strcmp(view, "band-link-refused-max") == 0) {
        st->link_refused = UINT32_MAX;
    }
    if (strncmp(view, "band-fault", 10) == 0) {
        st->faults = (strcmp(view, "band-fault-all") == 0) ? 0xFFu : 0x51u;
        chip = UI_BAND_CHIP_FAULT;
    } else if (strcmp(view, "band-bench") == 0
               || strcmp(view, "band-sim") == 0) {
        chip = UI_BAND_CHIP_MODE;
    } else if (strcmp(view, "band-inject") == 0) {
        /* A build with RCBENCH_TOUCH_INJECTOR and an injector attached. */
        st->mode = ui_band_mode_inject();
        chip = UI_BAND_CHIP_MODE;
    } else if (strcmp(view, "band-clock") == 0) {
        chip = UI_BAND_CHIP_CLOCK;
    } else if (strncmp(view, "band-armed", 10) == 0
               || strcmp(view, "band-safe") == 0) {
        chip = UI_BAND_CHIP_ARMED;
        st->armed = strcmp(view, "band-safe") != 0;
        st->armed_roles =
            (strcmp(view, "band-armed") == 0) ? UI_ARMED_MOTOR
            : (strcmp(view, "band-armed-servo") == 0) ? UI_ARMED_SERVO
            : (uint8_t)0u;
    }
    ui_router_set_status(st);
    gfx_rect_t r;
    if (ui_band_chip_rect(st, chip, &r)) {
        tap(r.x + r.w / 2, r.y + r.h / 2);
    }
}

/**
 * @brief MOTOR's run and SUPPLY's offline views: the samples, the bindings and
 *        the PD mini.
 * @param id      The screen of the shot.
 * @param view    The golden's name.
 * @param mo_prog The view is one of MOTOR's PROGRAM or ESC STICK views.
 */
static void pose_motor_supply(ui_screen_id_t id, const char *view,
                              bool mo_prog)
{
    /*
     * A scripted run, so the bench screenshot shows the same moment every
     * time: spin up, hold, a burst, then settle.  One sample per plot column
     * at the panel's poll rate, 20Hz.
     */
    if (id == SCREEN_MOTOR && (strcmp(view, "motor-idle") == 0
                               || strcmp(view, "motor-port") == 0)) {
        /* A linked bench before its first run: no sample, never armed, and
         * a binding read with no pin bound as a motor. */
        motor_screen_set_throttle_pins(0u, true);
        if (strcmp(view, "motor-port") == 0) {
            /* A 4.28 IOmcu with PROG PORT 2 as DSHOT300 on GP14. */
            port_view_t v;
            port_view_unknown(&v);
            v.count     = 4u;
            v.has_func  = true;
            v.has_dshot = true;
            v.pin[0]    = 13u;
            v.pin[1]    = 14u;
            v.func[0]   = (uint8_t)LINK_PG_FN_SERVO_PWM;
            v.func[1]   = (uint8_t)LINK_PG_FN_DSHOT300;
            v.func[2]   = v.func[3] = (uint8_t)LINK_PG_FN_NONE;
            port_view_set(&v);
        }
    } else if (mo_prog) {
        motor_screen_set_armed(false);
        motor_screen_set_throttle_pins(1u, true);
        motor_screen_set_throttle_protocol(proto_named("DSHOT300"));
    } else if (id == SCREEN_MOTOR) {
        telemetry_sim_t tsim;
        bench_state_t bench;
        memset(&bench, 0, sizeof(bench));
        telemetry_sim_init(&tsim, NULL);
        /* The run's totals as the panel counts them, from what it shows. */
        bench_totals_t totals;
        bench_totals_reset(&totals);
        /* Before the samples, not after: the plot advances only while the
         * bench is armed, and arming clears it.  Posed the other way round
         * the trace would be empty. */
        motor_screen_set_armed(true);
        for (int i = 0; i < 780; ++i) {
            const float t = (float)i * 0.05f;
            float th = 0.0f;
            if (t < 4.0f)                { th = 0.0f; }
            else if (t < 12.0f)          { th = 22.0f; }
            else if (t < 20.0f)          { th = 46.0f; }
            else if (t < 24.0f)          { th = 88.0f; }
            else if (t < 30.0f)          { th = 30.0f; }
            else                         { th = 64.0f; }
            telemetry_sim_step(&tsim, th, 0.05f, &bench);
            if (strcmp(view, "motor-table") == 0
                || strcmp(view, "motor-refused") == 0) {
                /* An IOmcu reading an INA228: BENCH's numbers are the
                 * INA228's, and the ESC's own telemetry reads 0.18V and
                 * 12% of the current high beside them. */
                bench.flags = (uint16_t)((bench.flags
                                          & (uint16_t)~LINK_BN_SIMULATED)
                                         | LINK_BN_SENSED);
                bench_state_set_esc(&bench, true, bench.voltage + 0.18f,
                                    true, bench.current * 1.12f, false);
            }
            bench_totals_count(&totals, &bench, 0.05f, true);
            bench_totals_show(&totals, &bench);
            motor_screen_push(&bench);
        }
        motor_screen_set_throttle(64.0f);
        /* Two pins bound as motors, as the panel reads them from the
         * binding. */
        motor_screen_set_throttle_pins(((uint64_t)1u << 0) | ((uint64_t)1u << 1),
                                       true);
        /* Bound as DSHOT300, entry 4 of the outputs catalogue. */
        motor_screen_set_throttle_protocol(4u);
        /* The run ends for the held view, so the trace stops where the last
         * sample left it and the panel says it is holding one; SETTINGS'
         * views are of a SAFE bench after a run, but the one ARMED. */
        if (strcmp(view, "motor-held") == 0
            || (strncmp(view, "motor-settings", 14) == 0
                && strcmp(view, "motor-settings-armed") != 0)) {
            motor_screen_set_armed(false);
        }
    }

    if (id == SCREEN_SUPPLY && strncmp(view, "supply-offline", 14) == 0) {
        /*
         * The PD mini enabled on GP12 and GP13 and not answering, the
         * output never switched on: the header in the warning colour, the
         * cards without readings and the plot empty.
         */
        const supply_caps_t caps = SUPPLY_CAPS_PDMINI;
        supply_screen_set_caps(&caps);
        supply_screen_settings_loaded();
        supply_screen_set_model(false);
        supply_screen_set_pins(12, 13);
        supply_state_t st;
        memset(&st, 0, sizeof(st));
        st.set_v  = 6.0f;
        st.set_i  = 2.0f;
        st.online = false;
        supply_screen_push(&st);
        if (strcmp(view, "supply-offline-settings") == 0) {
            /* The fit check's: SETTINGS with the PD mini, RESET PD MINI
             * under the start values, and the longest save line, a change
             * on SETUP nobody asked to keep. */
            ui_router_goto(SCREEN_SUPPLY);
            tap(SU_TAB_SETTINGS_X, UI_BAND_H + SU_TAB_Y);
            settings_set(SET_SUPPLY_TRIP_MS, 300.0f);
        }
    } else if (id == SCREEN_SUPPLY) {
        /* A run of the panel's model, as the panel drives it: the output on
         * at 6V and a 2A limit, the load's bursts holding the limit, the
         * extremes and totals counted from the switch-on. */
        supply_sim_t m;
        supply_sim_init(&m);
        supply_sim_set(&m, 6.0f, 2.0f);
        supply_state_t st;
        memset(&st, 0, sizeof(st));
        /* Limits an operator testing a standard servo would set: an HV
         * servo's 8.4V cap and a trip under the stall current. */
        settings_set(SET_SUPPLY_V_MAX, 8.4f);
        settings_set(SET_SUPPLY_TRIP_I, 2.5f);
        settings_set(SET_SUPPLY_TRIP_MS, 200.0f);
        /* As the overlay does when one is changed there: a save asked for,
         * which the harness has no flash to take. */
        settings_request_save();
        supply_screen_settings_loaded();
        supply_screen_set_model(true);
        supply_sim_output(&m, true);
        supply_sim_step(&m, 0.0f, &st);
        supply_reset_peaks(&st);
        supply_reset_totals(&st);
        supply_screen_set_output(true);
        for (int i = 0; i < 520; ++i) {
            supply_sim_step(&m, 0.05f, &st);
            supply_track_peaks(&st);
            supply_count_totals(&st, 0.05f);
            supply_screen_push(&st);
        }
        /*
         * The tasks and the overlays, opened the way a finger opens them.
         * Geometry from ui_workbench.h, supply_screen.c and ui_keypad.c,
         * offset by the band: SETTINGS, the strip's second tab, the VOLT
         * card at the top of the rail, and the keypad's 7, point and 4 from
         * a probe opened where the screen opens its own, over the left
         * column under the strip.
         */
        if (strcmp(view, "supply-settings") == 0) {
            ui_router_goto(SCREEN_SUPPLY);
            tap(SU_TAB_SETTINGS_X, UI_BAND_H + SU_TAB_Y);
        } else if (strcmp(view, "supply-confirm") == 0) {
            /* +0.1V on a live output: the question, as the settings'
             * default asks it. */
            ui_router_goto(SCREEN_SUPPLY);
            tap(SU_UP_X, UI_BAND_H + SU_V_ROW_Y);
        } else if (strcmp(view, "supply-keypad") == 0) {
            ui_router_goto(SCREEN_SUPPLY);
            tap(SU_CARD_X, UI_BAND_H + SU_CARD_Y(0));
            ui_keypad_t kp;
            memset(&kp, 0, sizeof(kp));
            ui_keypad_open(&kp, SU_OV_AREA, "", "", 0.0f, 0.0f, 1.0f, 2);
            const ui_key_t k[] = { UI_KEY_7, UI_KEY_DOT, UI_KEY_4 };
            for (size_t i = 0; i < sizeof(k) / sizeof(k[0]); ++i) {
                const gfx_rect_t r = ui_keypad_key_rect(&kp, k[i]);
                tap(r.x + r.w / 2, UI_BAND_H + r.y + r.h / 2);
            }
        } else if (strncmp(view, "supply-trip-", 12) == 0) {
            /* The fit check's: the output switched off by either trip. */
            st.output = false;
            st.trip = (view[12] == 'i') ? SUPPLY_TRIP_CURRENT
                                        : SUPPLY_TRIP_VOLTAGE;
            supply_screen_set_output(false);
            supply_screen_push(&st);
        } else if (strcmp(view, "supply-table") == 0) {
            /* The fit check's: LIVE's TABLE, every row with a reading. */
            ui_router_goto(SCREEN_SUPPLY);
            tap(SU_TABLE_TAB_X, UI_BAND_H + SU_PANE_Y);
        } else if (strcmp(view, "supply-port") == 0) {
            /* The fit check's: a servo programming port holds the
             * supply, the set points faint and MODE's line saying why. */
            supply_screen_set_port_held(true);
        }
    }
}

