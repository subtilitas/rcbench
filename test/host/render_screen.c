/* A canvas's own coordinates on the panel: a sub-canvas shares the
 * framebuffer, so its offset is where its first pixel sits in it. */
static void to_panel(const gfx_canvas_t *c, int *x, int *y)
{
    const ptrdiff_t off = c->pixels - fb;
    *x += (int)(off % W);
    *y += (int)(off / W);
}

void gfx_trace_text(const gfx_canvas_t *c, int x, int y, int w, int h,
                    const char *s, const gfx_rect_t *box)
{
    if (s_trace == NULL || c == NULL || s == NULL || s[0] == '\0') {
        return;
    }
    int cx = c->clip.x, cy = c->clip.y;
    to_panel(c, &x, &y);
    to_panel(c, &cx, &cy);
    int bx = -1, by = -1, bw = -1, bh = -1;
    if (box != NULL) {
        bx = box->x;
        by = box->y;
        bw = box->w;
        bh = box->h;
        to_panel(c, &bx, &by);
    }
    fprintf(s_trace, "T %d %d %d %d %d %d %d %d %d %d %d %d %s\n", x, y, w, h,
            cx, cy, c->clip.w, c->clip.h, bx, by, bw, bh, s);
}

