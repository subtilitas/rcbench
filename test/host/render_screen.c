/* The bench servo's image with Max. Duty moved by @p d steps of the value
 * the tab shows, so that a file edited by hand, which holds the values as
 * shown, differs from the servo as well. */
static kst_image_t kfile_image(int d)
{
    kst_image_t img = sim_bench_image();
    uint16_t raw = kst_field_get(&img, KST_F_DUTY);
    int32_t was = 0, now = 0;

    (void)kst_field_display(KST_F_DUTY, raw, &was);
    for (int left = d < 0 ? -d : d; left > 0; --left) {
        do {
            raw = (uint16_t)(raw + (d < 0 ? -1 : 1));
            (void)kst_field_display(KST_F_DUTY, raw, &now);
        } while (now == was);
        was = now;
    }
    (void)kst_field_edit(&img, KST_F_DUTY, raw);
    return img;
}

/* The same as the other servo type. */
static kst_image_t kfile_other(int d)
{
    kst_image_t img = kfile_image(d);

    (void)kst_field_set(&img, KST_F_20K_SEL,
                        1u - kst_field_get(&img, KST_F_20K_SEL));
    return img;
}

/*
 * The servo files: the list, the name of a new one, and what a file comes
 * to.  True when @p v is one of these views.
 */
static bool kst_file_view(const char *v)
{
    const kst_image_t low = kfile_image(-2);
    const kst_image_t high = kfile_image(1);
    const kst_image_t other = kfile_other(-2);
    fake_card_t *fc = &g_rig.fc;
    fake_file_t *f;

    if (strncmp(v, "-file", 5) != 0 && strncmp(v, "-name", 5) != 0
        && strncmp(v, "-card", 5) != 0) {
        return false;
    }
    if (strcmp(v, "-card-none") == 0) {
        g_rig.card = false;
        rig_frame();
        ktap(kst_panel_value_rect(0, 2, 0));
        return true;
    }
    if (strcmp(v, "-files-none") == 0) {
        kfiles();
        return true;
    }
    if (strcmp(v, "-card-full") == 0) {
        kfiles();
        ktap(kst_panel_choice_rect(0));
        fc->fails = KST_PROG_CARD_FULL;
        ktap(ui_textkey_key_rect(kst_panel_textkey(), UI_TK_OK));
        ksettle();
        return true;
    }
    (void)fake_card_put(fc, "KST001", &low);
    (void)fake_card_put(fc, "KST002", &high);
    (void)fake_card_put(fc, "WING-L", &other);
    f = fake_card_put(fc, "HAND", &low);
    f->kind = KST_PROG_FILE_UNTYPED;
    f->type = 0;
    if (strcmp(v, "-files-next") == 0) {
        (void)fake_card_put(fc, "KST003", &low);
        (void)fake_card_put(fc, "KST004", &low);
        (void)fake_card_put(fc, "KST005", &low);
    }
    if (strcmp(v, "-file-v6") == 0) {
        /* The servo is of the other type and is read again. */
        const kst_image_t sv = kfile_other(0);

        memcpy(g_rig.sim.reg, sv.r, sizeof(sv.r));
        ktap(kst_panel_value_rect(0, 1, 0));
        ksettle();
        ktype(kst_prog_type_guess(kst_panel_model()));
        kfiles();
        kpick("KST001");
        ksettle();
        return true;
    }
    kfiles();
    if (strcmp(v, "-files") == 0 || strcmp(v, "-files-next") == 0) {
        return true;
    }
    if (strncmp(v, "-name", 5) == 0) {
        ktap(kst_panel_choice_rect(0));
        if (strcmp(v, "-name-exists") == 0 || strcmp(v, "-name-bad") == 0
            || strcmp(v, "-name-saved") == 0) {
            const char *name = strcmp(v, "-name-exists") == 0 ? "WING-L"
                               : strcmp(v, "-name-bad") == 0 ? "CON"
                                                             : "WING-R";
            static const char chars[] =
                "1234567890QWERTYUIOPASDFGHJKL-ZXCVBNM_.";

            ktap(ui_textkey_key_rect(kst_panel_textkey(), UI_TK_CLR));
            for (; *name != '\0'; ++name) {
                ktap(ui_textkey_key_rect(kst_panel_textkey(),
                                         (int)(strchr(chars, *name) - chars)));
            }
            ktap(ui_textkey_key_rect(kst_panel_textkey(), UI_TK_OK));
            ksettle();
        }
        return true;
    }
    if (strcmp(v, "-file-loaded") == 0) {
        kpick("KST001");
    } else if (strcmp(v, "-file-edited") == 0) {
        fake_card_find(fc, "KST001")->kind = KST_PROG_FILE_EDITED;
        kpick("KST001");
    } else if (strcmp(v, "-file-untyped") == 0
               || strcmp(v, "-file-locked") == 0) {
        /* No type line and the 20k value of the other type. */
        fake_card_find(fc, "HAND")->img = other;
        kpick("HAND");
    } else if (strcmp(v, "-file-type") == 0) {
        kpick("WING-L");
    } else if (strcmp(v, "-file-same") == 0) {
        fake_card_find(fc, "KST001")->img = sim_bench_image();
        kpick("KST001");
    } else if (strcmp(v, "-file-damaged") == 0) {
        fake_card_find(fc, "KST001")->result = KST_PROG_CARD_CHECKSUM;
        kpick("KST001");
    } else if (strcmp(v, "-file-bad") == 0) {
        f = fake_card_find(fc, "KST001");
        f->result = KST_PROG_CARD_BAD;
        f->line = 12;
        kpick("KST001");
    } else if (strcmp(v, "-file-newer") == 0) {
        fake_card_find(fc, "KST001")->result = KST_PROG_CARD_NEWER;
        kpick("KST001");
    } else if (strcmp(v, "-file-hard") == 0) {
        f = fake_card_find(fc, "HAND");
        f->result = KST_PROG_CARD_VALUE;
        f->field = KST_F_DUTY;
        f->line = 9;
        kpick("HAND");
    } else if (strcmp(v, "-file-soft") == 0) {
        fake_card_find(fc, "KST002")->kind = KST_PROG_FILE_EDITED;
        kpick("KST002");
    }
    ksettle();
    if (strcmp(v, "-file-locked") == 0) {
        ktap(kst_panel_tab_rect(4));
    }
    return true;
}

/*
 * SERVO > PROGRAM's list: the registry's KST and Hitec rows on the
 * tester's PROG PORT 1, live with the pin the feed carries
 * (servo-program); dimmed PORT IN USE while the programming ports' page
 * says the HITEC page holds port 1 and the Hitec programmer has not read
 * that page yet (servo-program-busy; once it has, its overlay opens with
 * RELEASE PORT, servo-hitec-other); with no IOmcu answering, dimmed with
 * their reason (servo-program-nocap).
 */
static void program_view(const char *view)
{
    rig_fresh();
    prog_registry_set_ports(
        strcmp(view, "servo-program-nocap") == 0 ? PROG_REG_NO_PORT : 0u,
        strcmp(view, "servo-program-busy") == 0 ? 0x1u : 0u);
    if (strcmp(view, "servo-program-many") == 0) {
        /* The fit check only: a table of 12 rows under two headings,
         * SEARCH and the page keys over them, one row dimmed. */
        static prog_reg_row_t many[12];
        for (int i = 0; i < 12; ++i) {
            many[i] = (prog_reg_row_t){
                PROG_DEV_SERVO, UI_WB_PROGRAM, TX_PL_KST,
                (i >= 3) ? TX_SV_TARGET_PORT : TX_PL_GRP_PROG_PORT,
                TX_SV_TARGET_PORT, 0u,
                (i == 1) ? (uint16_t)LINK_CAP_CELLS
                         : (uint16_t)LINK_CAP_SERVO_PWM,
                &kst_panel_pages, false };
        }
        prog_registry_use(many, 12);
    }
    if (strcmp(view, "servo-program") == 0
        || strcmp(view, "servo-program-busy") == 0
        || strcmp(view, "servo-program-many") == 0) {
        (void)rig_link_up(LINK_PROTOCOL_MINOR);
        render_hitec_feed(false);
    }
    ui_router_goto(SCREEN_SERVO);
    if (strcmp(view, "servo-program-nocap") != 0) {
        servo_screen_set_drive(1u, 13u, true);    /* the tester on PORT 1 */
    }
    tap(SV_TAB_PROGRAM_X, UI_BAND_H + SV_TAB_Y);
    ui_router_tick(0.02f);
}

/*
 * The programmer on SERVO, driven by taps against the simulated servo of
 * kst_sim.h on programming port 1.  Geometry from kst_panel.h: PROGRAM in
 * the strip, then its KST row on the list.
 */
static void kst_view(const char *view)
{
    const char *v = view + strlen("servo-kst");
    const bool nopage = strcmp(v, "-nopage") == 0;
    const bool cut = strcmp(v, "-doubt") == 0 || strcmp(v, "-journal") == 0
                  || strcmp(v, "-restore-list") == 0
                  || strcmp(v, "-restore") == 0
                  || strcmp(v, "-other") == 0;

    const bool supply = strcmp(v, "-supply") == 0
                     || strcmp(v, "-options") == 0
                     || strcmp(v, "-voltage") == 0 || strcmp(v, "-hv") == 0
                     || strcmp(v, "-wait") == 0
                     || strcmp(v, "-supplied") == 0
                     || strcmp(v, "-leave-supply") == 0;
    /* The PD mini's output on before CONNECT: the views of the cycle. */
    const bool on = strcmp(v, "-supply-on") == 0
                 || strcmp(v, "-cycling") == 0
                 || strcmp(v, "-cycle-cut") == 0
                 || strcmp(v, "-written-supply") == 0
                 || strcmp(v, "-leave-cycle") == 0
                 || strcmp(v, "-left-cycled") == 0;

    rig_fresh();
    g_rig.card = true;
    g_rig.rail = supply || on;
    if (on) {
        g_rig.sup_on = true;
        g_rig.sup_mv = 5000u;
        g_rig.sup_ma = 1000u;
    }
    g_rig.load_ma = 37u;
    g_rig.no_pin = strcmp(v, "-nopin") == 0;
    if (strcmp(v, "-target") == 0) {
        g_rig.target = 0u;
    }
    if (strcmp(v, "-readonly") == 0) {
        g_rig.sim.reg[0x06] = 0x05u;
    }
    (void)rig_link_up(nopage ? (uint16_t)(LINK_MINOR_KST - 1u)
                             : LINK_PROTOCOL_MINOR);
    ui_router_goto(SCREEN_SERVO);
    /* The tester's drive as the control task reports it: PORT 1 on GP13
     * when SERVO's target is the programmer's port, as program_view() sets
     * it; no pin when the generator has none for the port.  With the target
     * elsewhere (-target) the screen keeps SERVO PWM on its own pin. */
    if (g_rig.target != 0u) {
        servo_screen_set_drive(g_rig.target,
                               g_rig.no_pin ? SERVO_SCREEN_NO_PIN : RIG_PIN,
                               true);
    }
    if (strcmp(v, "-hv") == 0) {
        /* HV SERVO in the AUTOMATIC TEST card's settings on TEST, which
         * the programmer's voltage follows. */
        tap(SV_TAB_TEST_X, UI_BAND_H + SV_TAB_Y);
        tap(SV_RUN_SET_X, UI_BAND_H + SV_RUN_SET_Y(0));
        tap(SV_LIST_X(0), UI_BAND_H + SV_LIST_ROW_Y(2)); /* HV SERVO */
        tap(SV_TAB_LIVE_X, UI_BAND_H + SV_TAB_Y);
    }
    tap(SV_TAB_PROGRAM_X, UI_BAND_H + SV_TAB_Y);    /* PROGRAM */
    tap(SV_PROG_ROW_X, UI_BAND_H + SV_PROG_ROW_Y(0)); /* KST row */
    ui_router_tick(0.02f);
    if (v[0] == '\0' || nopage || strcmp(v, "-target") == 0
        || strcmp(v, "-supply") == 0 || strcmp(v, "-supply-on") == 0) {
        return;
    }
    if (strcmp(v, "-options") == 0 || strcmp(v, "-voltage") == 0
        || strcmp(v, "-hv") == 0 || strcmp(v, "-wait") == 0) {
        /* MORE with the port in the tester's hands: what CONNECT sets. */
        ktap(kst_panel_value_rect(0, 2, 1));
        if (strcmp(v, "-options") == 0) {
            return;
        }
        ktap(kst_panel_choice_rect(strcmp(v, "-wait") == 0 ? 2 : 0));
        if (strcmp(v, "-hv") == 0) {
            kkey(UI_KEY_CLR);
            kkey(UI_KEY_7);
            kkey(UI_KEY_DOT);
            kkey(UI_KEY_4);
            kkey(UI_KEY_OK);
        }
        return;
    }
    ktap(kst_panel_value_rect(0, 0, 0));            /* CONNECT */
    if (strcmp(v, "-nopin") == 0) {
        ksettle();
        return;
    }
    if (strcmp(v, "-supplied") == 0 || strcmp(v, "-leave-supply") == 0) {
        ksettle();
        if (strcmp(v, "-leave-supply") == 0) {
            ktap(kst_panel_value_rect(0, 0, 0));    /* LEAVE */
            ksettle();
        }
        return;
    }
    if (strcmp(v, "-working") == 0) {
        rig_frames(40);
        ui_router_tick(0.02f);
        return;
    }
    if (strcmp(v, "-cycling") == 0 || strcmp(v, "-cycle-cut") == 0) {
        /* In the 1s the output is off. */
        rig_frames(400);
        ui_router_tick(0.02f);
        if (strcmp(v, "-cycle-cut") == 0) {
            ktap(kst_panel_value_rect(0, 0, 0));    /* ABORT */
            ksettle();
        }
        return;
    }
    ksettle();
    if (strcmp(v, "-read") == 0 || strcmp(v, "-readonly") == 0) {
        return;
    }
    if (strcmp(v, "-type") == 0) {
        ktap(kst_panel_value_rect(0, 1, 1));        /* TYPE */
        return;
    }
    if (strcmp(v, "-type-first") == 0) {
        /* A file tapped with the type not set. */
        const kst_image_t img = *kst_prog_servo(kst_panel_model());

        (void)fake_card_put(&g_rig.fc, "KST001", &img);
        kfiles();
        kpick("KST001");
        return;
    }
    /* The operator sets the type: V8, where the views of TYPE show the
     * other type than 20k_sel suggests; elsewhere the one suggested. */
    ktype(strcmp(v, "-type-set") == 0
              ? (kst_prog_type_guess(kst_panel_model()) == 6u ? 8u : 6u)
              : kst_prog_type_guess(kst_panel_model()));
    if (strcmp(v, "-type-set") == 0) {
        return;
    }
    if (strcmp(v, "-swapped") == 0) {
        /* Another servo put on the port in the session, and read. */
        g_rig.sim.reg[0x10] ^= 0x01u;
        ktap(kst_panel_value_rect(0, 1, 0));        /* READ ALL */
        ksettle();
        return;
    }
    if (strcmp(v, "-locked") == 0) {
        ktap(kst_panel_tab_rect(4));
        return;
    }
    if (strcmp(v, "-failsafe") == 0) {
        ktap(kst_panel_tab_rect(3));
        return;
    }
    if (strcmp(v, "-enable") == 0) {
        ktap(kst_panel_value_rect(0, 3, 0));
        return;
    }
    if (strcmp(v, "-leave") == 0) {
        kedits();
        ktap(kst_panel_value_rect(0, 0, 0));
        return;
    }
    if (strcmp(v, "-leave-plain") == 0) {
        /* No write in the session: the supply stays as it is. */
        ktap(kst_panel_value_rect(0, 0, 0));
        return;
    }
    if (strcmp(v, "-more") == 0 || strcmp(v, "-release") == 0) {
        if (strcmp(v, "-release") == 0) {
            kenable();
        }
        ktap(kst_panel_value_rect(0, 2, 1));
        if (strcmp(v, "-release") == 0) {
            ktap(kst_panel_choice_rect(2));
        }
        return;
    }
    if (strcmp(v, "-keypad") == 0) {
        ktap(kst_panel_tab_rect(2));
        ktap(kst_panel_value_rect(2, 1, 1));        /* PULSE UPPER */
        return;
    }
    if (strcmp(v, "-stretch") == 0) {
        ktap(kst_panel_tab_rect(1));
        ktap(kst_panel_value_rect(1, 2, 0));
        return;
    }
    if (strcmp(v, "-soft") == 0) {
        ktap(kst_panel_tab_rect(1));
        ktap(kst_panel_value_rect(1, 1, 0));        /* MAX. DUTY */
        kkey(UI_KEY_CLR);
        kkey(UI_KEY_9);
        kkey(UI_KEY_7);
        kkey(UI_KEY_OK);
        return;
    }
    if (strcmp(v, "-hard") == 0) {
        /* SPEED LIMIT on with SPEED below the least the core takes. */
        ktap(kst_panel_tab_rect(1));
        ktap(kst_panel_value_rect(1, 3, 0));
        return;
    }
    if (strcmp(v, "-tune") == 0 || strcmp(v, "-pulse") == 0) {
        kedits();
        if (strcmp(v, "-pulse") == 0) {
            const kst_image_t *sv = kst_prog_servo(kst_panel_model());

            kedit(KST_F_NEUTRAL,
                  (uint16_t)(kst_field_get(sv, KST_F_NEUTRAL) + 5u));
        }
        ktap(kst_panel_tab_rect(strcmp(v, "-pulse") == 0 ? 2 : 1));
        return;
    }
    if (kst_file_view(v)) {
        return;
    }
    if (strcmp(v, "-restore-check") == 0) {
        /* Max. Duty and Boost written lower, and this session's backup,
         * which holds them higher, chosen in RESTORE. */
        const kst_image_t first = *kst_prog_servo(kst_panel_model());

        kenable();
        kedit(KST_F_DUTY, (uint16_t)(kst_field_get(&first, KST_F_DUTY) - 2u));
        kedit(KST_F_BOOST, (uint16_t)(kst_field_get(&first, KST_F_BOOST) - 4u));
        ktap(kst_panel_value_rect(0, 4, 1));
        khold();
        ksettle();
        ktap(kst_panel_value_rect(0, 4, 0));        /* RESTORE */
        kpick(ui_tr(TX_KP_FROM_SESSION));
        return;
    }
    /* The rest writes. */
    if (strcmp(v, "-write-nocard") == 0 || strcmp(v, "-nofile") == 0) {
        /* No card in the slot at the session's first write. */
        g_rig.card = false;
        rig_frame();
    }
    kenable();
    kedits();
    if (strcmp(v, "-changes") == 0) {
        ui_router_tick(0.02f);
        return;
    }
    ktap(kst_panel_value_rect(0, 4, 1));            /* WRITE n VALUES */
    if (strcmp(v, "-write") == 0 || strcmp(v, "-write-nocard") == 0) {
        return;
    }
    khold();
    if (strcmp(v, "-writing") == 0) {
        /* Under way: the first register is written, the rest is not. */
        for (unsigned i = 0; i < 30000u && g_rig.sim.n_writes == 0u; ++i) {
            rig_frame();
        }
        ui_router_tick(0.02f);
        return;
    }
    if (!cut) {
        ksettle();                                  /* -written */
        if (strcmp(v, "-leave-cycle") == 0 || strcmp(v, "-leave-note") == 0
            || strcmp(v, "-left-cycled") == 0
            || strcmp(v, "-left-note") == 0) {
            ktap(kst_panel_value_rect(0, 0, 0));    /* LEAVE */
            if (strncmp(v, "-left", 5) == 0) {
                khold();
                ksettle();
            }
        }
        return;
    }
    /* The link goes after the write's first register. */
    for (unsigned i = 0; i < 30000u && g_rig.sim.n_writes == 0u; ++i) {
        rig_frame();
    }
    kst_link_lost(&g_rig.link);
    g_rig.safe = false;
    rig_frames(200);
    g_rig.safe = true;
    (void)rig_link_up(LINK_PROTOCOL_MINOR);
    ui_router_tick(0.02f);
    if (strcmp(v, "-doubt") == 0) {
        return;
    }
    if (strcmp(v, "-other") == 0) {
        /* Another servo on the port: 20k_sel is not the journal's. */
        kst_image_t img;

        memcpy(img.r, g_rig.sim.reg, sizeof(img.r));
        (void)kst_field_set(&img, KST_F_20K_SEL,
                            1u - kst_field_get(&img, KST_F_20K_SEL));
        memcpy(g_rig.sim.reg, img.r, sizeof(img.r));
    }
    ktap(kst_panel_value_rect(0, 1, 0));            /* READ ALL */
    ksettle();
    if (strcmp(v, "-journal") == 0 || strcmp(v, "-other") == 0) {
        return;
    }
    kenable();
    ktap(kst_panel_value_rect(0, 4, 0));            /* RESTORE */
    if (strcmp(v, "-restore") == 0) {
        ktap(kst_panel_choice_rect(0));
    }
}

/*
 * The automatic test on an armed bench, started the way a finger starts it
 * -- START TEST on the TEST page held for two seconds -- and run against the
 * servo model and a supply that does what SUPPLY asks: the running view
 * stops on the first step's movements, the result view runs it out and the
 * card takes its files as run 12.
 */
static void servo_run_view(bool to_the_end, bool ina)
{
    servo_sim_t sv;
    servo_sim_cfg_t cfg;
    servo_sim_defaults(&cfg);
    cfg.stop_lo_us = 1000u;
    cfg.stop_hi_us = 2000u;
    servo_sim_init(&sv, &cfg);
    sv.position_us = 1500.0f;
    settings_set(SET_SERVO_LEN_BY, 1.0f);
    settings_set(SET_SERVO_LEN_MOVES, 4.0f);
    settings_set_text(SET_TEXT_DUT_NAME, "DS3218 #2");
    servo_screen_set_armed(true);
    /* Nothing measures the horn on this bench: it is drawn chasing the
     * command. */
    servo_screen_feedback(0u, 0.0f, false);
    uint32_t now = 100000u;
    uint16_t samples = 1u;
    bool out = true;          /* the model's run above left it on */
    uint16_t cmd = 1500u;
    servo_screen_clock(now);
    if (ina) {
        /* The INA3221 on in SETUP and the rail's meter: the run reads its
         * windows, one every 50ms. */
        settings_set(SET_INA_FIT(0), 1.0f);
        servo_screen_source(SERVO_SOURCE_INA3221, 2u);
    }
    uint16_t win_number = 0u;
    tap(SV_TAB_TEST_X, UI_BAND_H + SV_TAB_Y);       /* TEST */
    touch_event_t e = { .type = TOUCH_EVENT_DOWN,
                        .point = { .id = 1, .x = SV_START_X,
                                   .y = (int16_t)(UI_BAND_H + SV_START_Y(0)),
                                   .strength = 40 } };
    ui_router_event(&e);                            /* START TEST, held */
    for (int i = 0; i < 115; ++i) {
        now += 20u;
        servo_screen_clock(now);
        if (ina && (now / 50u) != ((now - 20u) / 50u)) {
            /* The windows go on under the finger: a run that starts
             * before the release ends after 200ms without one. */
            const int ma = (int)(servo_sim_step(&sv, cmd, now) * 1000.0f);
            sense_link_win_t w;
            memset(&w, 0, sizeof(w));
            w.number   = ++win_number;
            w.current  = true;
            w.voltage  = true;
            w.mean_ma  = (int16_t)ma;
            w.max_ma   = (int16_t)ma;
            w.min_ma   = (int16_t)ma;
            w.mean_mv  = (uint16_t)((int)(supply_screen_set_v() * 1000.0f)
                                    - ma / 4);
            w.min_mv   = w.mean_mv;
            w.taken_ms = now;
            w.stamped  = true;
            servo_screen_window(&w, SERVO_SOURCE_INA3221, 2u);
        }
        ui_router_tick(0.02f);
    }
    e.type = TOUCH_EVENT_UP;
    ui_router_event(&e);
    /* LIVE: the run's box over the dial. */
    tap(SV_TAB_LIVE_X, UI_BAND_H + SV_TAB_Y);
    const int frames = to_the_end ? 4000 : 660;
    int after = 50;               /* frames once it is over: the OFF lands */
    for (int i = 0; i < frames; ++i) {
        now += 20u;
        servo_screen_clock(now);
        supply_cmd_t c;
        while (supply_screen_poll_cmd(&c)) {
            out = c.off ? false : (c.on ? true : out);
        }
        supply_screen_set_output(out);
        servo_cmd_t sc;
        while (servo_screen_take(&sc)) {
            if (sc.kind == SERVO_CMD_POSITION) {
                cmd = sc.value_us;
            } else if (sc.kind == SERVO_CMD_RELEASE) {
                cmd = 1500u;
            }
        }
        const float a = out ? servo_sim_step(&sv, cmd, now) : 0.0f;
        if (ina && (now / 50u) != ((now - 20u) / 50u)) {
            const int ma = (int)(a * 1000.0f);
            const int mv = out
                ? (int)(supply_screen_set_v() * 1000.0f) - ma / 4 : 0;
            sense_link_win_t w;
            memset(&w, 0, sizeof(w));
            w.number   = ++win_number;
            w.current  = true;
            w.voltage  = true;
            w.mean_ma  = (int16_t)ma;
            w.max_ma   = (int16_t)ma;
            w.min_ma   = (int16_t)ma;
            w.mean_mv  = (uint16_t)mv;
            w.min_mv   = (uint16_t)mv;
            w.taken_ms = now;
            w.stamped = true;
            servo_screen_window(&w, SERVO_SOURCE_INA3221, 2u);
        }
        if (i % 5 == 0) {
            supply_state_t st;
            memset(&st, 0, sizeof(st));
            st.online = true;
            st.ok     = SUPPLY_OK_VOLTAGE | SUPPLY_OK_CURRENT;
            st.output = out;
            st.set_v  = supply_screen_set_v();
            st.set_i  = supply_screen_set_i();
            st.v      = out ? st.set_v - a * 0.05f : 0.0f;
            st.i      = a;
            st.p      = st.v * st.i;
            st.mode   = out ? SUPPLY_MODE_CV : SUPPLY_MODE_OFF;
            st.samples  = ++samples;
            st.taken_ms = now;
            st.stamped = true;
            supply_screen_set_output(out);
            supply_screen_push(&st);
            servo_screen_supply(&st);
        }
        ui_router_tick(0.02f);
        const char *text = NULL;
        while (servo_screen_test_peek(&text) != SERVO_TEST_OUT_NONE) {
            servo_screen_test_pop();
        }
        if (to_the_end && !servo_screen_testing() && i > 200
            && --after <= 0) {
            break;
        }
    }
    if (to_the_end) {
        servo_screen_test_files(12, true);
        ui_router_tick(0.02f);
    }
}

/*
 * The limit run of LIMITS, on the bench of the host tests (test_kst_panel_limrun.c):
 * the simulated KST servo on programming port 1, GP13, behind the servo
 * model, the horn where its NEUTRAL, PULSE LOWER, PULSE UPPER, LEFT ANGLE
 * and RIGHT ANGLE put it at 4us a count (kst_sim.h sim_horn_us()); its
 * stops at 1150 and 1880us; the INA3221's CH1 windows from it every 50
 * ms; a bench that goes SAFE and ARMED as the screen asks.  One frame of
 * the rig is 1ms.  The bench's PULSE MIN and MAX are STANDARD PWM's, 1000
 * and 2000us; the servo's PULSE LOWER and UPPER 900 and 2100us, so every
 * view but -range runs with SERVO PULSES at 1000-2000.
 *
 *   -ready    LIMITS with SEARCH+PROG and SERVO PULSES 1000-2000 chosen,
 *             before the hold
 *   -range    SEARCH+PROG with SERVO PULSES at KEEP: FAIL after the read,
 *             the servo's pulses outside PULSE MIN and MAX
 *   (none)    running, a probe after the third session
 *   -pass     SEARCH+PROG run out: PASS
 *   -found    SEARCH ONLY on the bench's own output, GP2: FOUND
 *   -stopped  STOP in the probe after the first write: ABORTED, RESTORE
 *             named
 *   -restore  STOP in the session after the first write, then READ ALL
 *             and RESTORE's list: the servo as the run found it
 *   -nopd     -ready, and then no PD mini answers: SEARCH+PROG and SERVO
 *             PULSES chosen and not offered
 */
static struct {
    servo_sim_t sv;
    uint16_t cmd;
    bool armed, prog, out;
    bool nopd;                  /* the supply's readings say no PD mini */
    uint16_t win_no;
    uint32_t win_end;
    float sum;
    unsigned n;
} s_lr;

static void limrun_ms(uint32_t ms)
{
    for (uint32_t k = 0; k < ms; ++k) {
        rig_frame();
        /* On the programming port the horn stands where the servo's
         * registers put it for the pulse; on GP2 at the pulse. */
        const uint16_t horn = s_lr.prog
                                  ? sim_horn_cmd(g_rig.sim.reg, s_lr.cmd,
                                                 4.0f, false)
                                  : s_lr.cmd;
        s_lr.sum += s_lr.out ? servo_sim_step(&s_lr.sv, horn, g_rig.ms)
                             : 0.0f;
        s_lr.n++;
        if ((int32_t)(g_rig.ms - s_lr.win_end) >= 0) {
            const int ma = (int)(s_lr.sum / (float)s_lr.n * 1000.0f + 0.5f);
            sense_link_win_t w;

            memset(&w, 0, sizeof(w));
            w.number   = ++s_lr.win_no;
            w.current  = true;
            w.voltage  = true;
            w.mean_ma  = (int16_t)ma;
            w.max_ma   = (int16_t)ma;
            w.min_ma   = (int16_t)ma;
            w.mean_mv  = s_lr.out ? (uint16_t)(6000 - ma / 4) : 0u;
            w.min_mv   = w.mean_mv;
            w.taken_ms = g_rig.ms;
            w.stamped  = true;
            servo_screen_window(&w, SERVO_SOURCE_INA3221, 2u);
            s_lr.win_end += 50u;
            s_lr.sum = 0.0f;
            s_lr.n = 0u;
        }
        if (g_rig.ms % 20u != 0u) {
            continue;
        }
        servo_screen_clock(g_rig.ms);
        supply_cmd_t sc;
        while (supply_screen_poll_cmd(&sc)) {
            s_lr.out = sc.off ? false : (sc.on ? true : s_lr.out);
        }
        supply_screen_set_output(s_lr.out);
        if (g_rig.ms % 100u == 0u) {
            /* SUPPLY's own readings, for its OUTPUT button: the servo
             * screen's run reads the INA3221 alone. */
            supply_state_t st;
            memset(&st, 0, sizeof(st));
            st.online   = !s_lr.nopd;
            st.ok       = SUPPLY_OK_VOLTAGE | SUPPLY_OK_CURRENT;
            st.output   = s_lr.out;
            st.set_v    = supply_screen_set_v();
            st.set_i    = supply_screen_set_i();
            st.v        = s_lr.out ? st.set_v : 0.0f;
            st.mode     = s_lr.out ? SUPPLY_MODE_CV : SUPPLY_MODE_OFF;
            st.taken_ms = g_rig.ms;
            st.stamped  = true;
            supply_screen_push(&st);
            if (s_lr.nopd) {
                servo_screen_supply(&st);
            }
        }
        if (s_lr.prog) {
            servo_screen_set_drive(
                1u, 13u,
                kst_prog_state(kst_panel_model()) == KST_PROG_PWM
                    && !kst_panel_holds_port());
        }
        servo_cmd_t c;
        while (servo_screen_take(&c)) {
            if (c.kind == SERVO_CMD_POSITION) {
                s_lr.cmd = c.value_us;
            } else if (c.kind == SERVO_CMD_RELEASE) {
                s_lr.cmd = 1500u;
            } else if (c.kind == SERVO_CMD_DISARM) {
                s_lr.armed = false;
            } else if (c.kind == SERVO_CMD_ARM
                       && !kst_panel_holds_port()
                       && kst_prog_state(kst_panel_model())
                              == KST_PROG_PWM) {
                /* The control task drops an ARM while the programmer holds
                 * the port. */
                s_lr.armed = true;
            }
        }
        g_rig.safe = !s_lr.armed;
        servo_screen_set_armed(s_lr.armed);
        ui_router_tick(0.02f);
        const char *text = NULL;
        while (servo_screen_test_peek(&text) != SERVO_TEST_OUT_NONE) {
            servo_screen_test_pop();
        }
    }
}

