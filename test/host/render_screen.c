/* logs-pages: a full card, every run and one file the bench did not
 * write, so the tab carries the widest count it can: "FILES 145 TO 192 OF
 * 1000" on the fourth page, which the fit check measures.  The runs are
 * BENCH, ESC and SERVO in turn, so the page shows the three writers in one
 * number order. */
#define PAGES_RUNS LOG_RUN_LAST
#define PAGES_NEXT 3
static bool g_pages_card;

static int fake_list(log_viewer_file_t *out, int max_entries,
                     log_viewer_page_t *page, void *ctx)
{
    (void)ctx;
    log_select_page_t sel;
    log_select_page_begin(&sel, out, max_entries, page);
    int n = 0;
    log_viewer_file_t f;
    memset(&f, 0, sizeof(f));
    if (g_pages_card) {
        for (int r = 1; r <= PAGES_RUNS; ++r, ++n) {
            log_name_build(f.name, sizeof(f.name),
                           (log_prefix_t)(r % (int)LOG_PREFIX_COUNT), r,
                           false);
            f.size = 9000u + (uint32_t)r * 37u;
            /* A run every 10 minutes, the last at 2026-10-26 09:41. */
            f.mtime = 1793007660 - (int64_t)(PAGES_RUNS - r) * 600;
            log_select_page_offer(&sel, &f);
        }
        snprintf(f.name, sizeof(f.name), "%s", "SWEEP_920KV.CSV");
        f.size = 4096;
        f.mtime = 1790755200;                   /* 2026-09-30 08:00 */
        log_select_page_offer(&sel, &f);
        ++n;
    } else {
        const log_fake_t *set = k_card;
        size_t count = sizeof(k_card) / sizeof(k_card[0]);
        if (strcmp(g_fake_dir, CARD_AUTO_LOGS) == 0) {
            set = k_bench;
            count = sizeof(k_bench) / sizeof(k_bench[0]);
        } else if (strcmp(g_fake_dir, CARD_USER_LOGS) == 0) {
            set = k_user;
            count = sizeof(k_user) / sizeof(k_user[0]);
        }
        n = offer_folder(&sel, set, count);
    }
    (void)log_select_page_end(&sel, page);
    return n;
}

