/* A simulated card, so the log screenshots show states the UI can reach
 * rather than an empty browser. */
static char g_csv[32768];
static log_mem_ctx_t g_csv_ctx;

static void make_log_csv(void)
{
    /*
     * A run in the logger's format: units in the header row, the shape the
     * fixtures use.
     *
     * Known limitation of the reader: a separate units row is read for its
     * units and also counted as a data row, so a file in that shape reports
     * its first row as unreadable cells.
     */
    telemetry_sim_t sim;
    bench_state_t   b;
    memset(&b, 0, sizeof(b));
    telemetry_sim_init(&sim, NULL);

    size_t n = (size_t)snprintf(g_csv, sizeof(g_csv),
                                "time (s);voltage (V);current (A);"
                                "power (W);rpm (rpm)\n");
    for (int i = 0; i < 320 && n + 80u < sizeof(g_csv); ++i) {
        const float t = (float)i * 0.05f;
        float th = 0.0f;
        if (t >= 1.0f && t < 5.0f)  { th = 24.0f; }
        else if (t < 9.0f)          { th = 58.0f; }
        else if (t < 11.0f)         { th = 92.0f; }
        else                        { th = 40.0f; }
        telemetry_sim_step(&sim, th, 0.05f, &b);
        n += (size_t)snprintf(g_csv + n, sizeof(g_csv) - n,
                              "%.2f;%.2f;%.2f;%.0f;%.0f\n",
                              (double)t, (double)b.voltage, (double)b.current,
                              (double)b.power, (double)b.rpm);
    }
}

/* A SERVO run as the logger writes it (log_writer_servo_row()): a sweep
 * from 1000 to 2000us and back every 8s on the PD mini at 6.00V, the
 * encoder's angle a step behind the pulse, rows every 53ms. */
static char g_servo_csv[65536];
static size_t g_servo_len;

static int servo_csv_write(void *ctx, const void *data, size_t len)
{
    (void)ctx;
    if (g_servo_len + len >= sizeof(g_servo_csv)) {
        return -1;
    }
    memcpy(g_servo_csv + g_servo_len, data, len);
    g_servo_len += len;
    g_servo_csv[g_servo_len] = '\0';
    return (int)len;
}

static void make_servo_csv(void)
{
    g_servo_len = 0u;
    g_servo_csv[0] = '\0';
    const log_sink_t sink = { .write = servo_csv_write, .flush = NULL,
                              .ctx = NULL };
    log_writer_t w;
    log_writer_init(&w, &sink);
    bench_state_t b;
    memset(&b, 0, sizeof(b));
    b.valid = true;
    bench_totals_t t;
    bench_totals_reset(&t);
    float angle = 0.0f;
    for (int i = 0; i < 300; ++i) {
        const float ts = 0.036f + 0.053f * (float)i;
        const float ph = fmodf(ts, 8.0f) / 8.0f;
        const float tri = (ph < 0.5f) ? ph * 2.0f : (1.0f - ph) * 2.0f;
        const float us = 1000.0f + 1000.0f * tri;
        const float target = (us - 1500.0f) * 0.09f;
        const float moving = fabsf(target - angle);
        angle += (target - angle) * 0.6f;
        /* Idle, the move, and the load that grows away from the center. */
        log_rail_t r;
        memset(&r, 0, sizeof(r));
        r.i  = 0.035f + 0.06f * moving + 0.004f * fabsf(angle);
        r.v  = 6.0f - 0.05f * r.i;
        r.p  = r.v * r.i;
        r.ok = (uint8_t)(SUPPLY_OK_VOLTAGE | SUPPLY_OK_CURRENT);
        log_rail_count(&t, &r, 0.053f, true);
        log_servo_t sv;
        log_servo_unpack(log_servo_pack(true, (uint16_t)lroundf(us), true,
                                        angle), false, &sv);
        (void)log_writer_servo_row(&w, ts, &b, &r, &sv);
    }
}

