/*
 * Renders real frames on the host so cachegrind can model the ESP32-S3's data
 * cache (64 KiB, 8-way, 64-byte lines).
 *
 * On the board the framebuffer lives in PSRAM (pseudo-static random-access
 * memory) behind that cache, so every D1 (level-1 data cache) miss is a
 * 64-byte fetch and every dirty eviction a 64-byte write back.  The miss
 * count is the bus traffic a frame costs, which is what sets the frame rate.
 *
 * Driven by tools/frame_cost.py.  Modes:
 *   frame     steady state: the band redrawn, screen chrome cached
 *   chrome    everything repainted every frame, i.e. the cost of not caching
 *   overview  the menu, whose tiles are chrome and are never in a frame
 *   servo     the servo card, whose arm and grip are drawn from coverage
 *   servo-grip  the same, repainting only the breathing grip
 *   servo-current  the same as servo-grip with the INA3221 as the servo
 *             rail's meter and a window every frame whose current differs
 *             in the digits shown: the grip, the CURRENT row's value, the
 *             line and the plot, each clipped to itself
 *   supply    the supply screen with its output on, a sample every frame
 *   supply-chrome  the same, repainted in full every frame
 *   sim       the same steady state with the SIMULATION watermark over it,
 *             the only mode that blends rather than writes
 *   frame-idle the bench between samples: the panel refreshes at 39 Hz and
 *             samples arrive at 20 Hz, so about half of all frames have
 *             nothing new to plot.  `frame` pushes one sample per frame and
 *             is the worst case, which is what the ceiling guards.
 *   clear     a full-screen clear, for reference
 *   vlines    17 full-height vertical lines, the pathological case
 *   hlines    the same pixel count as horizontal lines
 *   held      the motor screen between two runs, its plot full and the
 *             bench disarmed
 *   throttle  `frame` with the throttle control changing every frame, the
 *             drag case
 *   <screen>  one steady frame of analyser, logs, settings, battery,
 *             balance, motor-stick or picker; settings is SETUP's tiles,
 *             settings-list PANEL's list, motor-stick MOTOR & ESC's
 *             ESC STICK session under the output strip, on its makers
 *   <screen>-chrome  the same, repainted in full every frame
 *   <screen>-sim     the same with the SIMULATION watermark
 *
 * Any other mode name runs as `frame`; no error is raised for a typo.
 *
 * SPDX-License-Identifier: MIT
 */

#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include <string.h>

#include "gfx.h"
#include "out_bind.h"
#include "overview_screen.h"
#include "picker_screen.h"
#include "settings_screen.h"
#include "servo_screen.h"
#include "splash_screen.h"
#include "supply.h"
#include "supply_screen.h"
#include "telemetry_sim.h"
#include "ui_screen.h"
#include "motor_screen.h"
#include "ui_theme.h"
#include "ui_widgets.h"
#include "wifi_screen.h"

/* The IOmcu's board drawing, generated by tools/gen_board_drawing.py. */
extern const uint8_t  board_drawing_rp2350_can[];
extern const uint32_t board_drawing_rp2350_can_bytes;

#define W UI_PANEL_W
#define H UI_PANEL_H

static gfx_color_t fb[W * H];

static const ui_bench_status_t k_status = {
    .link_up = true, .armed = true, .faults = 0,
    .run_seconds = 257, .mode = "BENCH",    /* ui_band_mode(true) */
    /* Not read in this harness; the strip prints "--". */
    .mcu_temp_c = NAN,
};

/*
 * argv is (frames, mode).  frame_cost.py measures the difference between a
 * 1-frame run and an 11-frame run, so process start-up, the first paint into
 * each buffer and the cachegrind harness cancel out.  The frame count is
 * therefore honoured exactly.
 */
int main(int argc, char **argv)
{
    const int   frames = (argc > 1) ? atoi(argv[1]) : 1;
    const char *mode   = (argc > 2) ? argv[2] : "frame";

    gfx_canvas_t c;
    gfx_canvas_init(&c, fb, W, H, W);
    ui_theme_set(UI_THEME_DARK);
    ui_router_init();
    ui_router_set_status(&k_status);

    if (strcmp(mode, "clear") == 0) {
        for (int i = 0; i < frames; ++i) {
            gfx_clear(&c, (gfx_color_t)(0x1234 + i));
        }
        return 0;
    }
    if (strcmp(mode, "vlines") == 0) {
        for (int f = 0; f < frames; ++f) {
            for (int i = 0; i < 17; ++i) {
                gfx_fill_rect(&c, i * 47, 0, 1, H, (gfx_color_t)(0x4321 + f));
            }
        }
        return 0;
    }
    if (strcmp(mode, "hlines") == 0) {
        /* The same pixel count as vlines, drawn as rows.  The difference is
         * the cost of column-major drawing. */
        for (int f = 0; f < frames; ++f) {
            for (int i = 0; i < 17; ++i) {
                gfx_fill_rect(&c, 0, i * 28, H, 1, (gfx_color_t)(0x4321 + f));
            }
        }
        return 0;
    }

    const size_t mode_len = strlen(mode);
    const bool want_sim =
        (strcmp(mode, "sim") == 0)
        || (mode_len > 4 && strcmp(mode + mode_len - 4, "-sim") == 0);
    if (want_sim) {
        ui_bench_status_t sim = k_status;
        sim.simulated = true;
        ui_router_set_status(&sim);
    }

    const bool servo = (strncmp(mode, "servo", 5) == 0);
    const bool supply = (strncmp(mode, "supply", 6) == 0);
    ui_screen_id_t start = SCREEN_MOTOR;
    if (strcmp(mode, "overview") == 0) {
        start = SCREEN_OVERVIEW;
    } else if (supply) {
        start = SCREEN_SUPPLY;
        supply_screen_set_model(true);
        supply_screen_set_output(true);
    } else if (servo) {
        start = SCREEN_SERVO;
    }
    /* The screens that carry no mode of their own: what one steady frame of
     * each costs once both framebuffers hold its chrome. */
    static const struct { const char *name; ui_screen_id_t id; } k_plain[] = {
        { "analyser",   SCREEN_ANALYSER },
        { "logs",       SCREEN_LOGS },
        { "settings",   SCREEN_SETUP },
        { "settings-list", SCREEN_SETUP },
        { "battery",    SCREEN_BATTERY },
        { "balance",    SCREEN_BALANCE },
        { "motor-stick", SCREEN_MOTOR },
        /* The picker with the IOmcu's drawing of the RP2350-CAN: an
         * outline, 102 shapes and 40 pad rings on a full repaint. */
        { "picker",     SCREEN_PICKER },
        /* WI-FI with the access point up; "wifi-keys" is the same
         * screen with the Wi-Fi keyboard open, a key typed every frame. */
        { "wifi-keys",  SCREEN_WIFI },
        { "wifi",       SCREEN_WIFI },
    };
    bool plain = false;
    bool plain_chrome = false;
    for (size_t k = 0; k < sizeof(k_plain) / sizeof(k_plain[0]); ++k) {
        const char *n = k_plain[k].name;
        const size_t len = strlen(n);
        if (strcmp(mode, n) == 0) {
            start = k_plain[k].id;
            plain = true;
            break;
        }
        /* "<screen>-chrome": the same screen repainting in full every frame,
         * which is what an invalidation on every frame costs. */
        if (strncmp(mode, n, len) == 0 && strcmp(mode + len, "-chrome") == 0) {
            start = k_plain[k].id;
            plain = true;
            plain_chrome = true;
            break;
        }
        /* "<screen>-sim": the same screen with the SIMULATION watermark, which
         * the panel paints over the whole canvas on every frame. */
        if (strncmp(mode, n, len) == 0 && strcmp(mode + len, "-sim") == 0) {
            start = k_plain[k].id;
            plain = true;
            break;
        }
    }
    if (start == SCREEN_PICKER) {
        outbind_t b;
        outbind_init(&b);
        outbind_set_board(&b, (uint16_t)OUTBIND_BOARD_PICO_HEADER);
        outbind_set_proto(&b, 1u);                 /* SERVO PWM */
        picker_screen_set_binding(&b);
        (void)picker_screen_set_drawing(board_drawing_rp2350_can,
                                        board_drawing_rp2350_can_bytes, NULL);
    }
    ui_router_goto(start);

    if (strncmp(mode, "motor-stick", 11) == 0) {
        /* PROGRAM, the strip's second tab at x 181, and its STICK MENU row
         * at (279, 65): the session opens full width. */
        static const int16_t at[2][2] = { { 181, 18 }, { 279, 65 } };
        for (int k = 0; k < 2; ++k) {
            const int16_t x = at[k][0];
            const int16_t y = (int16_t)(UI_BAND_H + at[k][1]);
            const touch_event_t tap[] = {
                { .type = TOUCH_EVENT_DOWN,
                  .point = { .id = 1, .x = x, .y = y } },
                { .type = TOUCH_EVENT_UP,
                  .point = { .id = 1, .x = x, .y = y } },
            };
            ui_router_event(&tap[0]);
            ui_router_event(&tap[1]);
        }
    }

    if (strncmp(mode, "settings-list", 13) == 0) {
        /* SETUP opens on its tiles: the first, PANEL, opens its list. */
        gfx_rect_t r = gfx_rect_make(0, 0, 0, 0);
        (void)settings_hub_slot(0, &r);
        const int16_t x = (int16_t)(r.x + r.w / 2);
        const int16_t y = (int16_t)(UI_BAND_H + r.y + r.h / 2);
        const touch_event_t tile[] = {
            { .type = TOUCH_EVENT_DOWN, .point = { .id = 1, .x = x, .y = y } },
            { .type = TOUCH_EVENT_UP,   .point = { .id = 1, .x = x, .y = y } },
        };
        ui_router_event(&tile[0]);
        ui_router_event(&tile[1]);
    }

    if (start == SCREEN_WIFI) {
        wifi_view_t v;
        memset(&v, 0, sizeof(v));
        v.code_on = true;
        strcpy(v.name, "rcbench-3F7A");
        strcpy(v.pass, "k7mqx3ha");
        strcpy(v.code, "r4tcw9pe");
        v.radio = WIFI_RADIO_AP;
        v.channel = 6;
        v.idle_left_s = 600;
        if (strcmp(mode, "wifi-keys") == 0) {
            /* CHOOSE HOME NETWORK, a list of one, its row: the password
             * keyboard.  Every key typed repaints the whole screen. */
            v.radio = WIFI_RADIO_OFF;
            wifi_screen_set(&v);
            const touch_event_t taps[] = {
                { .type = TOUCH_EVENT_DOWN,
                  .point = { .id = 1, .x = 196, .y = 48 + 16 + 2 * 68 + 28 } },
                { .type = TOUCH_EVENT_UP,
                  .point = { .id = 1, .x = 196, .y = 48 + 16 + 2 * 68 + 28 } },
            };
            ui_router_event(&taps[0]);
            ui_router_event(&taps[1]);
            v.scanned = true;
            v.scan_n = 1;
            strcpy(v.scan[0], "Workshop 2.4");
            v.rssi[0] = -43;
            wifi_screen_set(&v);
            const touch_event_t row[] = {
                { .type = TOUCH_EVENT_DOWN,
                  .point = { .id = 1, .x = 116, .y = 48 + 16 + 20 } },
                { .type = TOUCH_EVENT_UP,
                  .point = { .id = 1, .x = 116, .y = 48 + 16 + 20 } },
            };
            ui_router_event(&row[0]);
            ui_router_event(&row[1]);
            plain_chrome = true;
        } else {
            wifi_screen_set(&v);
        }
    }

    if (servo) {
        /* A position is taken only on an armed bench.  The arm's flash
         * repaints ARM for UI_HOLD_FLASH_FRAMES drawn frames, which are no
         * part of a steady frame: it is spent here, before the warm renders. */
        servo_screen_set_armed(true);
        servo_screen_set_commanded(38.0f);
        if (strcmp(mode, "servo-current") == 0) {
            servo_screen_source(SERVO_SOURCE_INA3221, 1u);
        }
        for (int f = 0; f < 2 * UI_HOLD_FLASH_FRAMES; ++f) {
            ui_router_tick(0.0f);
            ui_router_render(&c, f & 1);
        }
    }

    /* The plot advances only while the bench is armed, and every motor mode
     * but "held" measures a running one, so the arm comes before the warm
     * renders and before the samples. */
    motor_screen_set_armed(true);

    telemetry_sim_t sim;
    bench_state_t bench;
    memset(&bench, 0, sizeof(bench));
    telemetry_sim_init(&sim, NULL);
    const bool feed = (strcmp(mode, "frame-idle") != 0);

    supply_sim_t   sup_sim;
    supply_state_t sup;
    memset(&sup, 0, sizeof(sup));
    supply_sim_init(&sup_sim);
    supply_sim_output(&sup_sim, true);

    /*
     * "held" measures the frame between two runs, so the run has to be over
     * before the first measured frame.  It is filled and ended here rather
     * than part way through the loop: this harness is invoked for 1 frame and
     * for 11, and the cost is the difference between them, so anything that
     * happens after frame 11 is never measured at all.
     */
    if (strcmp(mode, "held") == 0) {
        for (int i = 0; i < 200; ++i) {
            telemetry_sim_step(&sim, 60.0f, 0.05f, &bench);
            motor_screen_push(&bench);
        }
        motor_screen_set_armed(false);
    }

    /* Warm both framebuffers the way the panel does, before measuring. */
    ui_router_render(&c, 0);
    ui_router_render(&c, 1);

    for (int i = 0; i < frames; ++i) {
        if (plain) {
            if (plain_chrome) {
                ui_router_invalidate();
            }
            ui_router_tick(0.026f);
            ui_router_render(&c, i & 1);
            continue;
        }
        if (servo) {
            /* "servo" moves the arm every frame: the drag case, and the
             * worst one.  "servo-grip" holds it still, so only the grip
             * breathes, which is the frame the clipped repaint exists for. */
            if (strcmp(mode, "servo") == 0) {
                servo_screen_set_commanded(38.0f + (float)((i % 20) - 10));
            }
            servo_screen_feedback(servo_screen_commanded(), 0.4f, true);
            if (strcmp(mode, "servo-current") == 0) {
                /* A window in every frame: 20 close a second and the panel
                 * draws 39 frames, into two buffers in turn, so each window
                 * is painted twice and no frame is without one. */
                const sense_link_win_t w = {
                    .number  = (uint16_t)i,
                    .current = true, .voltage = true,
                    .mean_ma = (int16_t)(300 + 37 * (i % 9)),
                    .max_ma  = 900, .min_ma = 20,
                    .mean_mv = 5980u, .min_mv = 5900u,
                };
                servo_screen_window(&w, SERVO_SOURCE_INA3221, 1u);
            }
            ui_router_tick(0.026f);
            ui_router_render(&c, i & 1);
            continue;
        }
        if (supply) {
            /* A sample every frame is the plot's worst case, as `frame` is
             * the motor bench's. */
            supply_sim_step(&sup_sim, 0.05f, &sup);
            supply_screen_push(&sup);
            if (strcmp(mode, "supply-chrome") == 0) {
                ui_router_invalidate();
            }
            ui_router_tick(0.026f);
            ui_router_render(&c, i & 1);
            continue;
        }
        if (feed) {
            telemetry_sim_step(&sim, 60.0f, 0.05f, &bench);
            motor_screen_push(&bench);
        }
        if (strcmp(mode, "throttle") == 0) {
            /* A finger on the throttle: the control revision moves on every
             * frame, which is the drag case and the screen's worst one. */
            motor_screen_set_throttle((float)(i % 100));
        }
        if (strcmp(mode, "chrome") == 0) {
            /* Nothing cached: what repainting the chrome every frame costs. */
            ui_router_invalidate();
        }
        ui_router_render(&c, i & 1);
    }
    return 0;
}
